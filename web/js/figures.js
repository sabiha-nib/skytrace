// Figure export: any chart on screen can be saved as a standalone SVG that carries its context with it: target,
// synthetic status, investigation content hash, analysis and method versions, and the export time. The plotted marks
// are the on-screen ones (drawn from recorded values); only the styling is changed for print (light background).

import { state } from "./state.js";
import { download, el, toast } from "./util.js";

const PRINT_STYLE = `
svg.figure { background: #ffffff; font-family: Helvetica, Arial, sans-serif; }
.figure text { fill: #222; font-size: 11px; }
.figure .grid line { stroke: #e3e3e3; }
.figure .axis-line { stroke: #888; }
.figure .cat-line { stroke: #087f96; stroke-dasharray: 5 4; fill: none; }
.figure .thresh { stroke: #c0552d; stroke-dasharray: 3 3; }
.figure .f-title { font-size: 13px; font-weight: bold; }
.figure .f-meta { font-size: 10px; fill: #444; }
.figure .f-syn { font-size: 10px; fill: #a0306c; font-weight: bold; }`;

const esc = (s) => String(s).replace(/[&<>"]/g, (c) => ({ "&": "&amp;", "<": "&lt;", ">": "&gt;", '"': "&quot;" })[c]);

export function figureSVG(chart, title) {
  const vb = chart.getAttribute("viewBox").split(/\s+/).map(Number);
  const [w, h] = [vb[2], vb[3]];
  const rec = state.inv?.record;
  const syn = !!state.model?.synthetic;
  const methods = rec?.parameters?.methods ? Object.values(rec.parameters.methods).flat().join(", ") : "";
  const lines = [
    `Target: ${rec?.target ?? state.targetId}${syn ? "" : " · archive data"}`,
    `Investigation ${rec?.content_hash?.slice(0, 16) ?? "—"} · ${rec?.parameters?.analysis_version ?? ""} · methods: ${methods}`,
    `Skytrace ${state.status?.version ?? ""}${state.status?.static ? " (static preview)" : ""} · exported ${new Date().toISOString()} · error bars are 1σ as recorded`,
  ];
  const head = 30, foot = 16 * (lines.length + (syn ? 1 : 0)) + 8;
  const meta = { title, target: rec?.target, synthetic: syn, content_hash: rec?.content_hash, parameters: rec?.parameters,
                 exported_at: new Date().toISOString(), skytrace: state.status?.version };
  const inner = new XMLSerializer().serializeToString(chart.cloneNode(true))
    .replace(/^<svg[^>]*>/, "").replace(/<\/svg>$/, "");
  return `<?xml version="1.0" encoding="UTF-8"?>
<svg xmlns="http://www.w3.org/2000/svg" class="figure" width="${w}" height="${h + head + foot}" viewBox="0 0 ${w} ${h + head + foot}">
<style>${PRINT_STYLE}</style>
<metadata>${esc(JSON.stringify(meta))}</metadata>
<rect width="100%" height="100%" fill="#ffffff"/>
<text class="f-title" x="10" y="20">${esc(title)}</text>
<svg x="0" y="${head}" width="${w}" height="${h}" viewBox="${vb.join(" ")}">${inner}</svg>
${syn ? `<text class="f-syn" x="10" y="${head + h + 16}">SYNTHETIC TEST DATA: generated by code, not an astronomical observation</text>` : ""}
${lines.map((l, i) => `<text class="f-meta" x="10" y="${head + h + 16 * (i + 1 + (syn ? 1 : 0))}">${esc(l)}</text>`).join("\n")}
</svg>`;
}

/** Add an "Export figure (SVG)" button under every chart inside a panel's cards. */
export function attachFigureExports(panel) {
  panel.querySelectorAll(".card").forEach((card) => {
    const chart = card.querySelector("svg.chart");
    if (!chart || card.querySelector(".fig-export")) return;
    const title = (card.querySelector("h3")?.textContent || "Skytrace figure").trim();
    const b = el("button", { class: "btn small ghost fig-export", type: "button", title: "Save this chart as an SVG with its target, investigation and method versions" }, "Export figure (SVG)");
    b.addEventListener("click", async () => {
      const name = `skytrace-${state.targetId}-${title.toLowerCase().replace(/[^a-z0-9]+/g, "-").replace(/^-|-$/g, "").slice(0, 40)}.svg`;
      if (await download(name, figureSVG(chart, title), "image/svg+xml")) toast("Figure exported");
    });
    chart.after(b);
  });
}

export const figureButton = attachFigureExports;
