export function card(title, ...children) { return el("div", { class: "card" }, title ? el("h3", {}, title) : null, ...children); }

export function details(summary, ...children) { return el("details", { class: "intel-more" }, el("summary", {}, summary), ...children); }

export function fmtNum(v, d = 3) {
  if (typeof v !== "number" || !Number.isFinite(v)) return v === null || v === undefined ? "—" : String(v);
  if (Number.isInteger(v) && Math.abs(v) < 1e9) return String(v);
  const a = Math.abs(v);
  return a !== 0 && (a >= 1e5 || a < 1e-3) ? v.toExponential(2) : a >= 100 ? v.toFixed(1) : v.toPrecision(d);
}

/** Element.append() turns null into the text "null"; conditional sections are skipped instead. */
export function put(node, ...xs) { node.append(...xs.filter((x) => x !== null && x !== undefined && x !== false)); return node; }
