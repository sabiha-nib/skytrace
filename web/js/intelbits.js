// Shared pieces of the Scientific Intelligence workspace: the data-kind legend that separates real data, synthetic data,
// simulated outputs, hypothetical scenarios, unverified interpretations and verified computations; status pills; small
// helpers. Every value shown comes from the server's intelligence report (or the preview's recording of it) or from the
// parity-tested browser core (intelcore.js).

import { el } from "./util.js";

export const KINDS = [
  ["real", "Real data", "read from SPHEREx archive files"],
  ["synthetic", "Synthetic data", "generated by code to test the pipeline; never evidence about the sky"],
  ["simulated", "Simulated output", "a deliberate perturbation (scaled errors, a generated scenario)"],
  ["hypothetical", "Hypothetical scenario", "something that did not happen: a what-if, a planned observation"],
  ["unverified", "Unverified interpretation", "an explanation, causal model or conclusion not established by the evidence"],
  ["verified", "Verified computation", "recomputed from recorded inputs and checked against the record"],
];
const KIND = Object.fromEntries(KINDS.map(([k, n, w]) => [k, [n, w]]));

export function kindChip(k) {
  const [name, why] = KIND[k] || [k, ""];
  return el("span", { class: `kind kind-${k}`, title: why }, name);
}

export function legend() {
  return el("div", { class: "kind-legend", role: "note", "aria-label": "What each label means" }, ...KINDS.map(([k, , w]) => el("span", { class: "kind-item" }, kindChip(k), el("span", { class: "faint small" }, w))));
}

