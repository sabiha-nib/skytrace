// Synthetic Observatory (SYNOBS-1) and Observation Design Lab (OBSDES-1). Generated scenarios test methods on known
// answers; they never replace observations. Schedules are hypothetical — Skytrace does not schedule a telescope.

import { api, STATIC } from "./api.js";
import { getSpecs, state } from "./state.js";
import * as S from "./session.js";
import { clear, download, el, renderToken, toast, $ } from "./util.js";

let tab = "scenarios", lastRun = null, lastDesign = null, busy = false;
export function setSyntheticTab(t) { tab = t; }

const fmt = (v, d = 3) => v === null || v === undefined ? "—" : typeof v === "number" ? (Math.abs(v) >= 100 ? v.toFixed(0) : v.toPrecision(d)) : String(v);

export async function renderSynthetic() {
  const live = renderToken("synthetic");
  const body = $("#synthetic-body");
  clear(body);
  const sp = (await getSpecs()).frontier.synthetic;
  if (!live()) return;
  body.append(el("div", { class: "tabs", role: "tablist", "aria-label": "Synthetic Observatory" }, ...[["scenarios", "Scenarios and ground truth"], ["design", "Observation Design Lab"]].map(([k, t]) => {
    const b = el("button", { type: "button", role: "tab", "aria-selected": String(tab === k), "data-stab": k }, t);
    b.addEventListener("click", () => { tab = k; renderSynthetic(); });
    return b;
  })));
  body.append(el("div", { class: "banner syn" }, el("strong", {}, "SYNTHETIC. "), "Every scenario here is generated by code (SYN-LAB-… targets, files marked SYNTHETIC = T) under data/synthlab/, never in the observation bundles. " +
    "Agreement on generated data tests the software against its own generator; it does not establish performance on real SPHEREx data."));
  if (tab === "scenarios") body.append(scenariosView(sp));
  else body.append(designView(sp));
}

function scenariosView(sp) {
  const tpl = el("select", { id: "syn-template", "aria-label": "Scenario template" }, ...sp.templates.map((t) => el("option", { value: t.id }, t.title)));
  const area = el("textarea", { id: "syn-json", rows: "9", class: "mono", "aria-label": "Scenario (JSON)", spellcheck: "false" });
  const fill = () => { area.value = JSON.stringify(sp.templates.find((t) => t.id === tpl.value).scenario, null, 1); };
  tpl.addEventListener("change", fill); fill();
  const run = el("button", { class: "btn primary", type: "button", id: "syn-run" }, "Generate and analyse");
  run.addEventListener("click", async () => {
    if (busy) return;
    let sc;
    try { sc = JSON.parse(area.value); } catch { toast("The scenario is not valid JSON"); return; }
    if (!STATIC && !run.dataset.armed) { run.dataset.armed = "1"; run.textContent = "Confirm: writes a synthetic bundle and runs the analysis (~5 s)"; return; }
    delete run.dataset.armed; run.textContent = "Generate and analyse";
    busy = true;
    const out = $("#syn-result");
    clear(out).append(el("p", { class: "busy" }, el("span", { class: "spinner" }), "Generating the scenario and running the unchanged pipeline…"));
    try {
      const r = await api.synthetic(sc);
      lastRun = r;
      await S.update("synthetic.run", `Synthetic scenario ${r.scenario_id}: ` + r.evaluation.rows.map((x) => `${x.question} ${x.verdict}`).join(", "), (s) => {
        s.synthetic = [...(s.synthetic || []).filter((x) => x.scenario_id !== r.scenario_id), { scenario_id: r.scenario_id, scenario: r.scenario,
          verdicts: Object.fromEntries(r.evaluation.rows.map((x) => [x.question, x.verdict])), categories: r.evaluation.categories,
          record_content_hash: r.record_content_hash, recorded_at_build: !!r.recorded_at_build }].slice(-30);
        return s;
      }, r.scenario_id);
      clear(out).append(resultView(r));
    } catch (e) { clear(out).append(el("p", { class: "withheld" }, e.message)); }
    busy = false;
  });
  const pos = Object.entries(sp.positions).map(([k, v]) => `${k} (y = ${v} px)`).join(", ");
  return el("div", {}, el("div", { class: "card" }, el("h3", {}, "Scenario"),
    el("p", { class: "muted" }, `Bounded fields: seed, pm_mas_yr [east, north], passes (2–6: day, detector position ${pos}, brightness factor, optional gain), noise, sky, target_flux_scale, ` +
      "reference_offset_arcsec, psf_sigma_scale. Brightness is comparable only between passes at the same position (the same wavelength)." +
      (STATIC ? " Static preview: only the templates are precomputed (generating files needs python run.py)." : "")),
    el("div", { class: "controls" }, tpl), area, el("div", { class: "controls" }, run)),
    el("div", { id: "syn-result" }, lastRun ? resultView(lastRun) : null), history());
}

function resultView(r) {
  const ev = r.evaluation;
  const exp = el("button", { class: "btn small", type: "button" }, "Export validation report (JSON)");
  exp.addEventListener("click", async () => { if (await download(`skytrace-synthetic-${r.scenario_id}.json`, JSON.stringify(r, null, 1), "application/json")) toast("Report exported"); });
  return el("div", { class: "card syn-result" }, el("h3", {}, `${r.scenario_id} · ${r.method}`),
    el("p", {}, el("span", { class: "pill sim" }, "synthetic"), r.recorded_at_build ? el("span", { class: "pill" }, "recorded when the preview was built") : null,
      el("span", { class: "pill" }, r.cache), el("span", { class: "faint mono" }, ` record ${r.record_content_hash.slice(0, 12)}… · seed ${r.scenario.seed}`)),
    el("div", { class: "table-wrap" }, el("table", { class: "syn-table" }, el("thead", {}, el("tr", {}, ...["Question", "Ground truth (generator input)", "Expected (stated rule)", "Pipeline output", "Measured", "Sensitivity", "Error", "Verdict"].map((h) => el("th", { scope: "col" }, h)))),
      el("tbody", {}, ...ev.rows.map((x) => el("tr", { class: `v-${x.verdict.split(" ")[0]}` }, el("th", { scope: "row" }, x.question), el("td", {}, x.truth), el("td", {}, x.expected),
        el("td", {}, x.pipeline || "—"), el("td", {}, fmt(x.measured)), el("td", {}, fmt(x.sensitivity)),
        el("td", {}, x.error ? `east ${fmt(x.error.east_sigma, 2)}σ, north ${fmt(x.error.north_sigma, 2)}σ` : "—"), el("td", {}, el("strong", {}, x.verdict))))))),
    el("ul", { class: "plain small" }, ...ev.rows.map((x) => el("li", { class: "faint" }, `${x.question}: ${x.rule}`))),
    el("p", {}, el("strong", {}, "Failure behaviour: "), Object.keys(ev.failure_behaviour.rejected_exposures_by_reason).length
      ? Object.entries(ev.failure_behaviour.rejected_exposures_by_reason).map(([k, v]) => `${v} exposure(s) refused as ${k}`).join("; ") : "no exposure refused",
      el("span", { class: "faint" }, ` — ${ev.failure_behaviour.note}`)),
    el("details", {}, el("summary", {}, "Assumptions and limitation"), el("ul", { class: "limits" }, ...r.assumptions.map((a) => el("li", {}, a)), el("li", {}, ev.limitation))),
    el("div", { class: "controls" }, exp));
}

function history() {
  const h = state.session?.synthetic || [];
  return el("div", { class: "card" }, el("h3", {}, "Synthetic scenarios in this session"), h.length ? el("ul", { class: "plain" }, ...h.slice().reverse().map((x) =>
    el("li", {}, el("span", { class: "mono" }, x.scenario_id), " · ", Object.entries(x.verdicts).map(([q, v]) => `${q}: ${v}`).join("; ")))) : el("p", { class: "muted" }, "None yet."));
}

function designView(sp) {
  const base = sp.templates[0].scenario;
  const truth = el("textarea", { id: "design-truth", rows: "3", class: "mono", "aria-label": "Truth (seed and motion)" }, JSON.stringify({ seed: base.seed, pm_mas_yr: base.pm_mas_yr }));
  const sched = el("textarea", { id: "design-schedules", rows: "10", class: "mono", "aria-label": "Hypothetical schedules (JSON list)" }, JSON.stringify([
    { name: "two passes, 6 months, same position", passes: [{ day: 0, position: "A", brightness: 1 }, { day: 182, position: "A", brightness: 1 }] },
    { name: "four passes over 18 months", passes: base.passes }], null, 1));
  const run = el("button", { class: "btn primary", type: "button", id: "design-run" }, "Compare schedules");
  run.addEventListener("click", async () => {
    if (busy) return;
    let t, s;
    try { t = JSON.parse(truth.value); s = JSON.parse(sched.value); } catch { toast("Truth and schedules must be valid JSON"); return; }
    if (!STATIC && !run.dataset.armed) { run.dataset.armed = "1"; run.textContent = `Confirm: generates ${Array.isArray(s) ? s.length : "?"} synthetic scenarios`; return; }
    delete run.dataset.armed; run.textContent = "Compare schedules";
    busy = true;
    const out = $("#design-result");
    clear(out).append(el("p", { class: "busy" }, el("span", { class: "spinner" }), "Generating each hypothetical schedule…"));
    try {
      const r = await api.design(t, s);
      lastDesign = r;
      await S.log("design.run", `Observation design: ${r.schedules.length} hypothetical schedules compared`, null, { create: true });
      clear(out).append(designResult(r));
    } catch (e) { clear(out).append(el("p", { class: "withheld" }, e.message)); }
    busy = false;
  });
  return el("div", {}, el("div", { class: "card" }, el("h3", {}, "Compare hypothetical observation schedules"),
    el("p", { class: "muted" }, `Each schedule is generated by ${sp.templates.length ? "SYNOBS-1" : ""} with the same truth and seed, then analysed by the unchanged pipeline. ` +
      `At most ${sp.design_max} schedules. Hypothetical: Skytrace does not schedule or command a telescope; the noise model is illustrative.` +
      (STATIC ? " Static preview: one comparison is precomputed; editing needs python run.py." : "")),
    el("label", { for: "design-truth" }, "Truth"), truth, el("label", { for: "design-schedules" }, "Schedules"), sched, el("div", { class: "controls" }, run)),
    el("div", { id: "design-result" }, lastDesign ? designResult(lastDesign) : null));
}

function designResult(r) {
  const exp = el("button", { class: "btn small", type: "button", id: "design-brief" }, "Export planning brief (Markdown)");
  exp.addEventListener("click", async () => { if (await download("skytrace-observation-brief.md", r.brief, "text/markdown")) toast("Brief exported"); });
  return el("div", { class: "card" }, el("h3", {}, "Schedule comparison"), el("p", {}, el("span", { class: "pill sim" }, "hypothetical · synthetic"),
    r.recorded_at_build ? el("span", { class: "pill" }, "recorded when the preview was built") : null),
    el("div", { class: "table-wrap" }, el("table", {}, el("thead", {}, el("tr", {}, ...["Schedule", "Passes", "Span (d)", "Positions", "Motion 5σ sensitivity (mas/yr)", "Motion", "Brightness sensitivity", "Brightness"].map((h) => el("th", { scope: "col" }, h)))),
      el("tbody", {}, ...r.schedules.map((x) => el("tr", {}, el("th", { scope: "row" }, x.name), el("td", {}, String(x.n_passes)), el("td", {}, fmt(x.span_days)), el("td", {}, x.positions),
        el("td", {}, fmt(x.motion_sensitivity_mas_yr)), el("td", {}, `${x.motion_category} (${x.motion_verdict})`), el("td", {}, x.brightness_sensitivity ? `${(x.brightness_sensitivity * 100).toFixed(1)} %` : "—"),
        el("td", {}, `${x.brightness_category} (${x.brightness_verdict})`)))))),
    el("p", { class: "faint" }, `${r.basis} ${r.caveat}`), el("div", { class: "controls" }, exp));
}
