"""Deterministic local assistant: the copilot's fallback when no language model is available.

It routes a question to tools by keywords, then writes the answer from fixed
templates filled only with values copied from the tool outputs. It offers no
interpretation beyond the deterministic outcomes, and its answers pass the
same guard as model answers. Every answer is labelled as model-free.
"""

from __future__ import annotations

import re

from .tools import ToolSession, call_tool

KEY_RE = re.compile(r"\b(?:QR\d|SYNTHETIC):[A-Za-z0-9_]+:D[1-6]\b")


def _f(x, nd=1):
    if x is None:
        return "n/a"
    if isinstance(x, float):
        return f"{x:.{nd}f}"
    return str(x)


def _intent(q: str) -> str:
    ql = q.lower()
    rules = [("alignment", r"align|registr|plate|astrometric frame"), ("compat", r"compatib|wavelength|match"),
             ("excluded", r"exclud|reject|why was|flag"), ("gaia", r"gaia|catalog|proper motion|motion"),
             ("uncertainty", r"uncertain|error bar|limitation|largest"), ("next", r"next|should i|investigate|follow"),
             ("support", r"support|which observations|evidence for"), ("changed", r"chang|vary|variab|differ|bright|dim")]
    for name, pat in rules:
        if re.search(pat, ql):
            return name
    return "summary"


def answer(question: str, s: ToolSession) -> dict:
    keys = KEY_RE.findall(question)
    intent = _intent(question)
    syn = s.view.is_synthetic()
    pre = "These are synthetic test data generated by code, not observations. " if syn else ""
    lims: list[str] = []
    claims: list[dict] = []
    lines: list[str] = []
    follow: list[str] = []

    summ = call_tool(s, "generate_investigation_summary", {})
    outcomes = {o["question"]: o for o in summ.output.get("outcomes", [])}
    for o in outcomes.values():
        lims += o["limitations"][:1]

    if intent in ("gaia", "alignment"):
        c = call_tool(s, "get_astrometric_validation", {})
        o = c.output
        if not o.get("available"):
            lines.append(f"No motion measurement is available: {o.get('reason')}.")
        else:
            fit, cat, cmp = o["fit"], o["catalogue"], o["comparison"]
            lines.append(f"The fitted motion is {_f(fit['pm_xi_mas_yr'], 0)} ± {_f(fit['sig_xi'], 0)} mas/yr east and "
                         f"{_f(fit['pm_eta_mas_yr'], 0)} ± {_f(fit['sig_eta'], 0)} mas/yr north, from {fit['n_epochs']} exposures "
                         f"over {_f(fit['baseline_yr'], 2)} yr.")
            lines.append(f"The catalogue values ({cat['source']}) are {_f(cat['pmra'], 0)} and {_f(cat['pmdec'], 0)} mas/yr; "
                         f"the differences are {_f(cmp['z_pmra'], 2)}σ and {_f(cmp['z_pmdec'], 2)}σ.")
            claims.append({"text": "fitted northward motion", "kind": "measurement", "value": fit["pm_eta_mas_yr"],
                           "unit": "mas/yr", "evidence": [c.id]})
            if intent == "alignment":
                lines.append(f"Registration scatter: the median plate-solution residual is {_f(o['median_plate_rms_mas'], 0)} mas "
                             f"per axis; {len(o['rejected_epochs'])} exposure(s) were rejected as outliers in the motion fit.")
            if o.get("outcome"):
                lines.append(f"Assessment ({o['outcome']['rules']}): {o['outcome']['statement']}")
        follow.append("Which exposures have the largest position residuals?")
    elif intent == "compat":
        if len(keys) >= 2:
            c = call_tool(s, "get_wavelength_compatibility", {"key_a": keys[0], "key_b": keys[1]})
            o = c.output
            if "error" in o:
                lines.append(f"I could not compare them: {o['error']}.")
            else:
                verdict = "can" if o["compatible_for_photometry"] else "cannot"
                lines.append(f"{o['a']} and {o['b']} {verdict} be compared photometrically: {o['reason']} (rule {o['rule']}).")
        else:
            wp = summ.output.get("wavelength_pairs")
            if wp:
                lines.append(f"{wp['accepted']} of {wp['considered']} observation pairs are wavelength-matched (rule {wp['rule']}).")
                if wp["rejection_reasons"]:
                    lines.append("Rejected pairs by reason: " + "; ".join(f"{k}: {v}" for k, v in wp["rejection_reasons"].items()) + ".")
                claims.append({"text": "matched pairs", "kind": "measurement", "value": wp["accepted"], "unit": "pairs",
                               "evidence": [summ.id]})
            else:
                lines.append("No pair comparison is recorded for this investigation.")
            lines.append("Only pairs from the same detector whose wavelengths at the target agree within half a channel "
                         "are compared photometrically; other differences mostly reflect the spectrum.")
        follow.append("Compare two specific observations, e.g. by selecting them in the Time Machine.")
    elif intent == "excluded":
        if keys:
            c = call_tool(s, "inspect_image_quality", {"key": keys[0]})
            o = c.output
            if "error" in o:
                lines.append(f"No record for {keys[0]}: {o['error']}.")
            elif o.get("included") is False:
                lines.append(f"{o['key']} was excluded at selection: {o.get('exclusion_reason')}.")
            else:
                lines.append(f"{o['key']}: status {o['status']}; quality \"{o['quality']}\".")
                if o.get("notes"):
                    lines.append("Notes: " + "; ".join(o["notes"][:3]) + ".")
        else:
            c = call_tool(s, "list_target_observations", {"status": "rejected", "limit": 8})
            o = c.output
            lines.append(f"{o['n_matching']} observation(s) were excluded or rejected.")
            for r in o["rows"][:6]:
                lines.append(f"{r['key']}: {r.get('exclusion_reason') or r.get('quality')}.")
        follow.append("Inspect the image quality of one rejected observation.")
    elif intent == "uncertainty":
        for o in outcomes.values():
            lines.append(f"{o['question'].replace('_', ' ').capitalize()}: {o['statement']}")
        ast = outcomes.get("motion", {}).get("evidence", {})
        if ast.get("pm_sigma_mas_yr") is not None:
            lines.append(f"The motion uncertainty is {_f(ast['pm_sigma_mas_yr'], 0)} mas/yr; the median registration "
                         f"residual is {_f(ast.get('median_plate_rms_mas'), 0)} mas per axis.")
        lines.append("Unmodelled systematics listed below are the largest open uncertainties.")
        lims = [l for o in outcomes.values() for l in o["limitations"]][:5]
    elif intent == "next":
        cats = {k: v["category"] for k, v in outcomes.items()}
        for k, v in outcomes.items():
            lines.append(f"{k.replace('_', ' ').capitalize()}: {v['statement']}")
        if cats.get("variability") == "variability_candidate":
            follow += ["Check whether the significant pairs share a detector region or a flagged neighbour.",
                       "Look for the same change in a second detector at a matched wavelength."]
        if cats.get("motion") in ("motion_inconsistent", "registration_limited"):
            follow.append("Inspect plate-solution residuals for the exposures with the largest position offsets.")
        if cats.get("variability") == "insufficient_evidence":
            follow.append("Acquire more epochs: no wavelength-matched pair exists yet.")
        follow.append("Re-run the analysis with a different aperture radius to test sensitivity.")
        lines.append("Suggested next steps are listed below; each one uses existing tools or re-runs the deterministic analysis.")
    else:  # changed / support / summary
        for o in outcomes.values():
            lines.append(f"{o['question'].replace('_', ' ').capitalize()} ({o['category'].replace('_', ' ')}): {o['statement']}")
        if intent in ("changed", "support"):
            fp = sorted(s.view.flux_pairs(), key=lambda p: -abs(p["z"]) if p.get("z") is not None else 0)
            if fp:
                c = call_tool(s, "compare_observation_epochs", {"key_a": fp[0]["a"], "key_b": fp[0]["b"]})
                o = c.output
                if o.get("flux"):
                    lines.append(f"The largest matched-wavelength difference is between {o['a']} ({o['t_a_iso']}) and "
                                 f"{o['b']} ({o['t_b_iso']}): {_f(o['flux']['flux_a_ujy'], 0)} → {_f(o['flux']['flux_b_ujy'], 0)} µJy, "
                                 f"z = {_f(o['flux']['z'], 1)} (a significance, not a probability).")
                    claims.append({"text": "largest matched-pair significance", "kind": "measurement", "value": o["flux"]["z"],
                                   "unit": "", "evidence": [c.id]})
        follow += ["Could the apparent motion be caused by alignment errors?", "Why was an observation excluded?"]
    if not claims:
        claims.append({"text": "deterministic outcomes", "kind": "measurement", "value": None, "unit": "", "evidence": [summ.id]})
    lims = list(dict.fromkeys(lims)) or ["The deterministic outcomes are only as complete as the observations available."]
    lims.append("Written by the local deterministic assistant without a language model; no interpretation is added.")
    return {"answer": pre + " ".join(lines), "claims": claims, "limitations": lims,
            "follow_up_questions": follow[:3], "suggested_next_steps": [], "intent": intent}
