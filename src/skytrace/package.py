"""Reproducibility package (PKG-1): one zip that lets someone else inspect, verify and replay an investigation.

Contents (no image data; replay needs the bundle, whose manifest is included):
  README.md            what the package is, how to verify the checksums and the record hash, how to replay
  record.json          the investigation record exactly as the server holds it (its content hash recomputes)
  report.md            the human-readable report
  discovery.json       DISC-1: inventory, questions and plans, HYPO-1 tests, UNC-1 decomposition, next steps
  evidence_graph.json  nodes and edges derived from the record
  capabilities.json    CAPREG-1 registry at packaging time
  bundle_manifest.json the data bundle's manifest (file SHA-256 and provenance)
  SHA256SUMS           checksum of every file above

The zip is deterministic: fixed member order and timestamps, so the same inputs give the same bytes.
"""

from __future__ import annotations

import hashlib
import io
import json
import zipfile

METHOD = "PKG-1"
_FIXED_TIME = (2020, 1, 1, 0, 0, 0)


def build(record_text: str, record: dict, report_md: str, discovery: dict, graph: dict, caps: dict,
          bundle_manifest: dict, software_version: str) -> bytes:
    synthetic = record.get("parameters", {}).get("bundle_kind") == "synthetic"
    readme = "\n".join([
        f"# Skytrace reproducibility package — {record.get('target')}",
        "",
        ("**SYNTHETIC TEST DATA.** The bundle was generated by code; nothing here is an astronomical observation."
         if synthetic else "Archive data; see bundle_manifest.json for each file's source and checksum."),
        "",
        f"* Record content hash: `{record.get('content_hash')}`",
        f"* Analysis version: {record.get('parameters', {}).get('analysis_version')} · Skytrace {software_version} · package {METHOD}",
        f"* Bundle: `{record.get('parameters', {}).get('bundle')}` (manifest SHA-256 `{record.get('parameters', {}).get('bundle_manifest_sha256')}`)",
        "",
        "## Verify",
        "",
        "1. `sha256sum -c SHA256SUMS` checks every file in this package.",
        "2. The record's content hash: SHA-256 of `json.dumps(record minus created_at, software and content_hash, "
        "sort_keys=True, separators=(',', ':'))` must equal `content_hash`.",
        "3. With the bundle present: `python scripts/verify_provenance.py <target> --record record.json --rerun` "
        "checks file hashes, origins, status codes and re-run determinism.",
        "",
        "## Replay",
        "",
        "Import `record.json` in Skytrace (Investigations → Import) or run the analysis with the parameters in "
        "`record.json` → `parameters`; an identical content hash means an identical result.",
        "",
        "## Limits",
        "",
        "No image data is included. Hypothesis statuses and uncertainty components are derived from the record by "
        "the rules named in discovery.json (HYPO-1, UNC-1); no probabilities are computed.",
        ""])
    files = {
        "README.md": readme,
        "record.json": record_text,
        "report.md": report_md,
        "discovery.json": json.dumps(discovery, indent=1, sort_keys=True, default=str),
        "evidence_graph.json": json.dumps(graph, indent=1, sort_keys=True, default=str),
        "capabilities.json": json.dumps(caps, indent=1, sort_keys=True, default=str),
        "bundle_manifest.json": json.dumps(bundle_manifest, indent=1, sort_keys=True, default=str),
    }
    sums = "".join(f"{hashlib.sha256(v.encode()).hexdigest()}  {k}\n" for k, v in files.items())
    files["SHA256SUMS"] = sums
    buf = io.BytesIO()
    with zipfile.ZipFile(buf, "w", zipfile.ZIP_DEFLATED) as z:
        for name, text in files.items():
            info = zipfile.ZipInfo(f"skytrace-{record.get('content_hash', '')[:16]}/{name}", date_time=_FIXED_TIME)
            info.compress_type = zipfile.ZIP_DEFLATED
            info.external_attr = 0o644 << 16
            z.writestr(info, text)
    return buf.getvalue()
