"""Epistemic engine (EPI-1): how each conclusion of an investigation is constructed, as a typed reasoning graph.

Source → Observation → Measurement → Derived quantity → Inference → Claim → Conclusion, with the transformations,
methods, models, assumptions, uncertainty, limitations, contradictions and competing hypotheses attached where the record
says they apply. Every node is built from a recorded value (the investigation record, the bundle manifest and the
derived reports DISC-1, HYPO-1 and LEDGER-1); nothing is inferred from wording.

Data edges point downstream ("measured from", "compared in", ...). Procedural context is attached through
transformation nodes (one per pipeline step) that point to every node that step produced, so tracing a claim backwards
reaches its methods, parameters, assumptions and uncertainty treatment without leaking into unrelated data.

Epistemic status (one of STATUSES) is assigned by STATUS_RULES from the node's origin and producing method — never from
the sentence that describes it. Procedural objects (transformations, methods) carry no status: they are not statements.
"""

from __future__ import annotations

from collections import Counter, deque

from . import canon, methodgenome as mg

METHOD = "EPI-1"
STATUSES = ["directly recorded", "measured", "derived", "model-dependent", "assumed", "hypothesized", "simulated",
            "user-authored", "unsupported", "unknown"]
KINDS = ["source", "observation", "measurement", "derived", "transformation", "method", "model", "assumption", "uncertainty",
         "inference", "hypothesis", "claim", "limitation", "contradiction", "conclusion"]
STATUS_RULES = {
    "S1": "a file or observation from a synthetic bundle is 'simulated' (generated by code, not recorded by an instrument)",
    "S2": "a file or observation from an archive bundle is 'directly recorded'",
    "S3": "a quantity takes the producing method's output status (METHOD-DNA-1: measured / derived / model-dependent), or the "
          "least direct status among its inputs if that is further from the data (order: measured < derived < model-dependent)",
    "S4": "analysis parameters, decision thresholds, models and method assumptions are 'assumed' (choices or premises, not results)",
    "S5": "a competing explanation (HYPO-1) is 'hypothesized'",
    "S6": "an inference (a stated rule applied to recorded values) is 'derived'",
    "S7": "a claim takes the least direct status among the inferences that decide it; a claim with no supporting item is 'unsupported'",
    "S8": "text written by the user in the session is 'user-authored' (applied in the browser)",
    "S9": "a value the record does not determine is 'unknown'",
    "S10": "uncertainty, limitation and contradiction records take the status of the rule that produced them ('derived') or are "
           "'assumed' when they state a premise",
}
ORDER = {"measured": 0, "derived": 1, "model-dependent": 2}
DATA_RELS = {"contains", "measured from", "positioned by", "compared in", "averaged into", "fitted in", "scale from", "decides",
             "concludes", "plate referenced to", "contradicts", "limits", "challenges", "tests"}
# which analysis parameters each pipeline step uses (record.parameters)
PARAM_STEPS = {"aperture_radius_px": "measure", "fit_half_size_px": "measure", "wavelength_tolerance_channels": "pairs",
               "wavelength_margin_um": "pairs", "photometry_same_release": "pairs", "detectors": "discover", "max_observations": "discover",
               "reader": "inspect", "epoch_clip_sigma": "astrometry", "epoch_gap_days": "astrometry", "apply_parallax": "astrometry",
               "reference_quality_cut": "references"}
STEP_METHODS = {"discover": [], "select": [], "references": ["REFSEL-2"], "inspect": [], "measure": ["FLAGPOL-1", "CENTROID-G2D-1", "APPHOT-1", "DIFFAST-1/PLATE-LOO-1"],
                "pairs": ["WLMATCH-2"], "variability": ["PAIRDIFF-1", "PAIRDIFF-2", "CALCHECK-1"], "astrometry": ["EPHEM-AA-LP-1", "LINFIT-EPOCH-1", "LINFIT-LOO-1"],
                "assess": ["ASSESS-2"]}
STEP_LABEL = {"discover": "Data ingestion (archive search / bundle discovery)", "select": "Selection", "references": "Reference catalogue",
              "inspect": "File validation (structure, units, keywords)", "measure": "Measurement (flags, centroid, photometry, plate solution)",
              "pairs": "Wavelength matching", "variability": "Flux comparison", "astrometry": "Visit averaging and motion fit",
              "assess": "Assessment"}
MODELS = [("model:gaussian_psf", "Elliptical 2-D Gaussian PSF", "CENTROID-G2D-1"), ("model:affine_plate", "6-parameter affine plate map", "DIFFAST-1/PLATE-LOO-1"),
          ("model:linear_motion", "Linear motion over the baseline", "LINFIT-EPOCH-1"), ("model:constant_refs", "Constant reference stars", "PAIRDIFF-2")]


def _ev(record):
    out = {}
    for i, e in enumerate(record["events"]):
        out.setdefault(e["step"], []).append((i, e))
    return out


def _least_direct(statuses):
    s = [x for x in statuses if x in ORDER]
    return max(s, key=ORDER.get) if s else None


class _G:
    def __init__(self):
        self.nodes, self.edges, self._ids = [], [], set()

    def node(self, nid, kind, label, status=None, rule=None, **attrs):
        if nid in self._ids:
            return nid
        self._ids.add(nid)
        n = {"id": nid, "kind": kind, "label": str(label)[:300], "status": status, "status_rule": rule}
        n.update({k: v for k, v in attrs.items() if v is not None})
        self.nodes.append(n)
        return nid

    def edge(self, a, b, rel, **attrs):
        if a in self._ids and b in self._ids:
            self.edges.append({"source": a, "target": b, "rel": rel, **attrs})


def build(record: dict, disc: dict, ledger: dict, manifest: dict | None = None) -> dict:
    """The reasoning graph of one investigation. `disc` is the DISC-1 report (with HYPO-1 and UNC-1), `ledger` LEDGER-1."""
    ev = _ev(record)
    params = record.get("parameters", {})
    synthetic = params.get("bundle_kind") == "synthetic"
    src_status, src_rule = ("simulated", "S1") if synthetic else ("directly recorded", "S2")
    out_status = {m["id"]: m["output_status"] for m in mg.METHODS}
    G = _G()
    files = {f["path"]: f for f in (manifest or {}).get("files", [])}

    # --- procedural context: transformations, methods, models, assumptions, parameters, uncertainty treatment
    steps_present = [s for s in STEP_LABEL if s in ev]
    for s in steps_present:
        G.node(f"tf:{s}", "transformation", STEP_LABEL[s], step=s, event=ev[s][0][0], n_events=len(ev[s]))
    used = mg.used_methods(record)
    for mid in sorted(used):
        m = mg.BY_ID.get(mid)
        G.node(f"method:{mid}", "method", mid + (f" — {m['purpose']}" if m else " (not in the method genome)"), registered=bool(m),
               output_status=m["output_status"] if m else None, module=m["module"] if m else None)
        if m:
            for k, a in enumerate(m["assumptions"]):
                G.node(f"asm:{mid}:{k}", "assumption", a, "assumed", "S4", source=f"METHOD-DNA-1 {mid}")
                G.edge(f"asm:{mid}:{k}", f"method:{mid}", "assumed by")
            G.node(f"unc:{mid}", "uncertainty", f"{mid}: {m['uncertainty_propagation']}", "derived" if not m["uncertainty_propagation"].startswith("none") else "assumed",
                   "S10", propagates=not m["uncertainty_propagation"].startswith("none"))
            G.edge(f"unc:{mid}", f"method:{mid}", "uncertainty treatment of")
    for s in steps_present:
        for mid in STEP_METHODS.get(s, []):
            G.edge(f"method:{mid}", f"tf:{s}", "used by")
    for mid_model, label, mid in MODELS:
        if f"method:{mid}" in G._ids:
            G.node(mid_model, "model", label, "assumed", "S4")
            G.edge(mid_model, f"method:{mid}", "model of")
    for k, v in params.items():
        if k in PARAM_STEPS and PARAM_STEPS[k] in ev:
            G.node(f"param:{k}", "assumption", f"analysis parameter {k} = {canon.dumps(v)}", "assumed", "S4", subtype="analysis choice", value=v)
            G.edge(f"param:{k}", f"tf:{PARAM_STEPS[k]}", "set")

    # --- data path
    ref_file = None
    if "references" in ev:
        i, e = ev["references"][0]
        d = e.get("data") or {}
        ref_file = G.node("file:catalogue", "source", f"reference catalogue ({d.get('catalogue') or 'catalogue'}, {d.get('n')} stars)", src_status, src_rule,
                          step="references", event=i, n=d.get("n"))
        G.edge("tf:references", ref_file, "produced")
    for i, e in ev.get("select", []):
        d = e.get("data") or {}
        G.node(f"obs:{d.get('key')}", "observation", f"{d.get('key')} (excluded at selection)", src_status, src_rule, step="select", event=i,
               excluded=True, reason=e.get("detail"))
        G.edge("tf:select", f"obs:{d.get('key')}", "produced")
    inspect = {(e.get("data") or {}).get("key"): (i, e) for i, e in ev.get("inspect", [])}
    for i, e in ev.get("measure", []):
        d = e.get("data") or {}
        key = d.get("obs_id")
        prov = (e.get("provenance") or [{}])[0]
        path = next((p for p, f in files.items() if f.get("sha256") == prov.get("content_sha256")), None)
        fid = G.node(f"file:{key}", "source", path or key, src_status, src_rule, sha256=prov.get("content_sha256") or None, origin=prov.get("origin"),
                     release=prov.get("release") or None, retrieved_at=prov.get("retrieved_at"), step="discover", event=i)
        G.edge("tf:discover", fid, "produced")
        ins = inspect.get(key)
        oid = G.node(f"obs:{key}", "observation", f"{key} · D{d.get('detector')} · MJD {d.get('mjd')}", src_status, src_rule, detector=d.get("detector"),
                     mjd=d.get("mjd"), step="inspect" if ins else "measure", event=ins[0] if ins else i,
                     image_bunit=(ins[1].get("data") or {}).get("image_bunit") if ins else None)
        G.edge(fid, oid, "contains")
        if ins:
            G.edge("tf:inspect", oid, "produced")
        ph, ce = d.get("photometry") or {}, d.get("centroid") or {}
        st = _least_direct([out_status.get(ph.get("method")), out_status.get(ce.get("method"))]) or "measured"
        mid = G.node(f"meas:{key}", "measurement", f"{key}: flux {_f(ph.get('flux_ujy'))} ± {_f(ph.get('flux_err_ujy'))} µJy · λ {_f(d.get('wavelength_um'), 4)} µm",
                     st, "S3", step="measure", event=i, quality=d.get("quality"), flux_ujy=ph.get("flux_ujy"), flux_err_ujy=ph.get("flux_err_ujy"),
                     wavelength_um=d.get("wavelength_um"), detector=d.get("detector"), methods=[x for x in (ce.get("method"), ph.get("method")) if x],
                     rejected=e.get("status") == "rejected" or None)
        G.edge(oid, mid, "measured from")
        G.edge("tf:measure", mid, "produced")
    # sky positions and visits
    astro = ev.get("astrometry", [])
    if astro:
        ai, ae = astro[0]
        ad = ae.get("data") or {}
        for s in ad.get("series", []):
            k = s.get("key")
            pid = G.node(f"pos:{k}", "derived", f"{k}: ξ {_f(s.get('xi_mas'), 1)} ± {_f(s.get('sig_xi_mas'), 1)} mas, η {_f(s.get('eta_mas'), 1)} ± {_f(s.get('sig_eta_mas'), 1)} mas",
                         _least_direct(["measured", out_status["DIFFAST-1/PLATE-LOO-1"]]), "S3", step="measure", event=ai, plate_rms_mas=s.get("plate_rms_mas"),
                         used_in_fit=s.get("used_in_fit"))
            G.edge(f"meas:{k}", pid, "positioned by")
            G.edge("file:catalogue", pid, "plate referenced to")
            G.edge("tf:measure", pid, "produced")
        for j, ep in enumerate(ad.get("epochs", [])):
            eid = G.node(f"epoch:{j}", "derived", f"visit {j + 1}: MJD {_f(ep.get('t_mjd'), 2)}, {ep.get('n_exposures')} exposures", "model-dependent", "S3",
                         step="astrometry", event=ai, n_exposures=ep.get("n_exposures"))
            keys = [s.get("key") for s in ad.get("series", [])]
            for k in ep.get("members") or []:       # members are indices into the position series
                if isinstance(k, int) and 0 <= k < len(keys):
                    G.edge(f"pos:{keys[k]}", eid, "averaged into")
            G.edge("tf:astrometry", eid, "produced")
        fit = ad.get("fit") or {}
        if fit:
            G.node("fit:motion", "derived", f"proper motion ξ {_f(fit.get('pm_xi_mas_yr'), 1)} ± {_f(fit.get('sig_xi'), 1)}, η {_f(fit.get('pm_eta_mas_yr'), 1)} ± {_f(fit.get('sig_eta'), 1)} mas/yr ({fit.get('method')})",
                   "model-dependent", "S3", step="astrometry", event=ai, n_epochs=fit.get("n_epochs"), method=fit.get("method"))
            for j in range(len(ad.get("epochs", []))):
                G.edge(f"epoch:{j}", "fit:motion", "fitted in")
            G.edge("tf:astrometry", "fit:motion", "produced")
    var = ev.get("variability", [])
    if var:
        vi, ve = var[0]
        vd = ve.get("data") or {}
        for p in vd.get("pairs", []):
            dif = p.get("differential") or {}
            cal = bool(dif.get("calibrated"))
            pid = G.node(_pid(p), "derived", f"{p['a']} ↔ {p['b']}: z = {_f(p.get('z'), 2)}" + (f", z_cal = {_f(dif.get('z_cal'), 2)}" if cal else " (uncalibrated)"),
                         "model-dependent" if cal else "derived", "S3", step="variability", event=vi, z=p.get("z"), z_cal=dif.get("z_cal") if cal else None,
                         calibrated=cal, delta_lambda_um=p.get("delta_lambda_um"))
            G.edge(f"meas:{p['a']}", pid, "compared in")
            G.edge(f"meas:{p['b']}", pid, "compared in")
            G.edge("tf:variability", pid, "produced")
        cc = vd.get("calibration_check") or {}
        if cc:
            G.node("scale:calcheck", "derived", f"photometric error scale {_f(cc.get('error_scale'), 3)} ({cc.get('status')}, {cc.get('n_ref_z')} reference comparisons)",
                   "model-dependent", "S3", step="variability", event=vi, value=cc.get("error_scale"))
            for p in vd.get("pairs", []):
                if (p.get("differential") or {}).get("calibrated"):
                    G.edge(_pid(p), "scale:calcheck", "scale from")
            G.edge("tf:variability", "scale:calcheck", "produced")
        if "pairs" in ev:
            G.edge("tf:pairs", "tf:variability", "precedes")

    # --- inference, claims, conclusion
    assess = ev.get("assess", [])
    if assess:
        si, se = assess[0]
        sd = se.get("data") or {}
        for k, v in (sd.get("thresholds") or {}).items():
            G.node(f"asm:threshold:{k}", "assumption", f"threshold {k} = {v} — {sd.get('threshold_provenance', '')[:120]}", "assumed", "S4", subtype="decision threshold")
        for o in sd.get("outcomes", []):
            q = o["question"]
            iid = G.node(f"inf:{q}", "inference", f"ASSESS-2 rule for {q}: {'; '.join(o.get('criteria') or [])[:220]}", "derived", "S6", step="assess", event=si)
            G.edge("tf:assess", iid, "produced")
            for k in _thresholds_for(q):
                G.edge(f"asm:threshold:{k}", iid, "decides")
            inputs = []
            if q == "variability":
                inputs = [n["id"] for n in G.nodes if n["id"].startswith("pair:")] + (["scale:calcheck"] if "scale:calcheck" in G._ids else [])
            elif q == "motion":
                inputs = ["fit:motion"] if "fit:motion" in G._ids else []
            elif q == "data_quality":
                inputs = [n["id"] for n in G.nodes if n["id"].startswith("meas:")]
            for x in inputs:
                G.edge(x, iid, "decides")
            sup = [n["status"] for n in G.nodes if n["id"] in inputs]
            has_support = bool(inputs)        # decided by recorded inputs (an absence claim is supported by the comparisons that found nothing)
            status = (_least_direct(sup + ["derived"]) if has_support else "unsupported")
            cid = G.node(f"claim:{q}", "claim", o.get("statement") or q, status, "S7", category=o.get("category"), question=q, step="assess", event=si)
            G.edge(iid, cid, "concludes")
            for j, lim in enumerate(o.get("limitations") or []):
                G.node(f"lim:{q}:{j}", "limitation", lim, "assumed" if lim.lower().startswith(("assum", "if ")) else "derived", "S10")
                G.edge(f"lim:{q}:{j}", cid, "limits")
        G.node("conclusion:investigation", "conclusion", "The investigation's conclusions: the claims below, each with its limitations and open alternatives",
               _least_direct([n["status"] for n in G.nodes if n["kind"] == "claim"]) or "unknown", "S7")
        for n in [n for n in G.nodes if n["kind"] == "claim"]:
            G.edge(n["id"], "conclusion:investigation", "concludes")
    for j, c in enumerate(ledger.get("contradictions", [])):
        cid = G.node(f"con:{j}", "contradiction", f"{c.get('kind')}: {c.get('detail')}", "derived", "S10", ledger_rule=c.get("rule"))
        a_b = c.get("items") or []
        for n in G.nodes:
            if n["id"].startswith("pair:") and len(a_b) == 2 and n["id"] == f"pair:{a_b[0]}|{a_b[1]}":
                G.edge(n["id"], cid, "contradicts")
        G.edge(cid, f"claim:{c['question']}" if f"claim:{c.get('question')}" in G._ids else ("claim:variability" if "z" in (c.get("detail") or "") else "conclusion:investigation"), "contradicts")

    # --- competing hypotheses and their tests
    for q in (disc.get("hypotheses") or {}).get("questions", []):
        target = f"claim:{q['question']}"
        for h in q.get("hypotheses", []):
            hid = G.node(f"hyp:{h['id']}", "hypothesis", f"{h['id']}: {h['statement']} — {h['overall']}", "hypothesized", "S5", overall=h["overall"])
            G.edge(hid, target, "challenges")
            for t in h.get("tests", []):
                tid = G.node(f"test:{h['id']}:{t['id']}", "inference", f"{t['id']} ({t['rule']}): {t['status']} — {t.get('detail', '')}"[:300], "derived", "S6",
                             test_status=t["status"])
                G.edge(f"inf:{q['question']}", tid, "tests")
                G.edge(tid, hid, "tests")

    counts = Counter(n["kind"] for n in G.nodes)
    status_counts = Counter(n["status"] for n in G.nodes if n["status"])
    return {"method": METHOD, "content_hash": record.get("content_hash"), "synthetic": synthetic, "statuses": STATUSES, "kinds": KINDS,
            "status_rules": STATUS_RULES, "nodes": G.nodes, "edges": G.edges, "counts": dict(counts), "status_counts": dict(status_counts),
            "claims": [n["id"] for n in G.nodes if n["kind"] == "claim"],
            "note": "Statuses describe how each statement was produced, not whether it is true."}


def _pid(p):
    return f"pair:{p['a']}|{p['b']}"


def _f(v, d=1):
    if isinstance(v, (int, float)):
        return f"{v:.{d}f}"
    return "—"


def _thresholds_for(q):
    return {"variability": ["variability_z", "min_matched_pairs", "calcheck_unreliable_scale"],
            "motion": ["motion_detect_sigma", "catalogue_consistency_sigma", "min_astrometric_exposures", "registration_ratio"],
            "data_quality": ["instrumental_fraction"]}.get(q, [])


NEGATORS = ("not", "no", "never", "without", "nor", "cannot")


def asserted_words(text: str, words) -> list:
    """Words from `words` that the text asserts: an occurrence preceded within four words (same sentence) by a negator ("not proof",
    "no evidence of discovery") is not an assertion. Mirrored in epistemiccore.js (parity-tested)."""
    low = (text or "").lower()
    hits = []
    for w in words:
        start = 0
        while True:
            i = low.find(w, start)
            if i < 0:
                break
            start = i + 1
            before_ok = i == 0 or not low[i - 1].isalnum()
            after = i + len(w)
            after_ok = after >= len(low) or not low[after].isalnum()
            if not (before_ok and after_ok):
                continue
            clause = low[:i]
            cut = max(clause.rfind(c) for c in ".!?;:")
            clause = clause[cut + 1:]               # a negator in an earlier sentence does not negate this one
            prev = "".join(c if c.isalnum() else " " for c in clause).split()[-4:]
            if not any(t in NEGATORS for t in prev):
                hits.append(w)
                break
    return sorted(set(hits))


def trace(graph: dict, node_id: str, direction: str = "back") -> dict:
    """Every node upstream ("back") or downstream ("forward") of node_id, with its distance. Mirrored in epistemiccore.js."""
    ids = {n["id"] for n in graph["nodes"]}
    if node_id not in ids:
        return {"start": node_id, "direction": direction, "nodes": [], "error": "unknown node"}
    adj: dict = {}
    for e in graph["edges"]:
        a, b = (e["target"], e["source"]) if direction == "back" else (e["source"], e["target"])
        adj.setdefault(a, []).append(b)
    dist = {node_id: 0}
    dq = deque([node_id])
    while dq:
        x = dq.popleft()
        for y in sorted(adj.get(x, [])):
            if y not in dist:
                dist[y] = dist[x] + 1
                dq.append(y)
    kinds = {n["id"]: n["kind"] for n in graph["nodes"]}
    found = sorted((d, i) for i, d in dist.items() if i != node_id)
    return {"start": node_id, "direction": direction, "nodes": [{"id": i, "depth": d} for d, i in found],
            "by_kind": dict(Counter(kinds[i] for _, i in found))}
