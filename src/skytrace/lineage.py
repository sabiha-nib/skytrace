"""Data lineage (LINEAGE-1): exactly how original files became a result.

For a result (a claim, the motion fit, or one flux comparison) the lineage lists the stages
original file → imported (manifest) → validated (structure, units) → transformed (flags, centroid, photometry, plate) →
measured → analysed → assessed → claim → report, each with the recorded transformation, its fingerprints and units, and
whether the record contains it. A stage the record does not contain is reported as missing, never filled in.
Coordinate and unit transformations are those the methods perform (WCS pixel → sky, affine plate to the tangent plane,
MJy/sr × pixel solid angle → µJy).
"""

from __future__ import annotations

from . import canon, epistemic as epi

METHOD = "LINEAGE-1"
STAGES = ["original file", "imported", "validated", "transformed", "measured", "analysed", "assessed", "claim", "report"]


def _ev(record):
    out = {}
    for i, e in enumerate(record["events"]):
        out.setdefault(e["step"], []).append((i, e))
    return out


def lineage(record: dict, manifest: dict | None, graph: dict, result_id: str, software_now: dict | None = None) -> dict:
    ev = _ev(record)
    ids = {n["id"]: n for n in graph["nodes"]}
    if result_id not in ids:
        return {"method": METHOD, "result": result_id, "error": "unknown result"}
    up = {x["id"] for x in epi.trace(graph, result_id)["nodes"]} | {result_id}
    keys = sorted(i[5:] for i in up if i.startswith("meas:"))
    files = {f.get("sha256"): f for f in (manifest or {}).get("files", [])}
    meas = {(e.get("data") or {}).get("obs_id"): (i, e) for i, e in ev.get("measure", [])}
    ins = {(e.get("data") or {}).get("key"): (i, e) for i, e in ev.get("inspect", [])}
    P = record.get("parameters", {})
    S = []

    def stage(name, present, transformation, fingerprints, units=None, note=None, events=None):
        S.append({"stage": name, "present": present, "transformation": transformation, "fingerprints": fingerprints, "units": units, "note": note,
                  "events": (events or [])[:20]})

    shas = [((meas[k][1].get("provenance") or [{}])[0]).get("content_sha256") for k in keys if k in meas]
    stage("original file", bool(shas) and all(shas), "archive file (or generated file for synthetic bundles)",
          [{"key": k, "sha256": s, "path": (files.get(s) or {}).get("path"), "origin": ((meas[k][1].get("provenance") or [{}])[0]).get("origin"),
            "retrieved_at": ((meas[k][1].get("provenance") or [{}])[0]).get("retrieved_at")} for k, s in zip(keys, shas)][:12],
          note=f"{len(keys)} file(s) feed this result" + ("; synthetic: generated by code" if P.get("bundle_kind") == "synthetic" else ""))
    in_manifest = [s for s in shas if s in files]
    stage("imported", bool(manifest) and len(in_manifest) == len(shas), "bundle manifest entry (SHA-256, bytes, provenance)",
          [{"manifest_sha256": P.get("bundle_manifest_sha256"), "files_in_manifest": len(in_manifest), "files": len(shas)}],
          note=None if manifest else "manifest not available here")
    det = lambda k: ((meas.get(k) or (0, {}))[1].get("data") or {}).get("detector")  # noqa: E731
    dets = {det(k) for k in keys} - {None}
    ins_dets = {det(k): (i, e) for k, (i, e) in ins.items() if det(k) is not None}
    iv = [ins_dets[d] for d in sorted(dets) if d in ins_dets]
    stage("validated", len(iv) == len(dets), "file structure, units and keywords read (inspect)",
          [{"key": (e.get("data") or {}).get("key"), "reader": (e.get("data") or {}).get("reader"), "extensions": (e.get("data") or {}).get("extensions"),
            "ctype": (e.get("data") or {}).get("ctype")} for _, e in iv][:6],
          units={"image": sorted({(e.get("data") or {}).get("image_bunit") for _, e in iv} - {None}), "variance": sorted({(e.get("data") or {}).get("variance_bunit") for _, e in iv} - {None})},
          note=f"structure inspected for {len(iv)} of {len(dets)} detector(s) involved (the pipeline inspects one file per detector and applies the result to that detector's files)",
          events=[i for i, _ in iv])
    mv = [meas[k] for k in keys if k in meas]
    stage("transformed", bool(mv), "FLAGPOL-1 pixel mask → CENTROID-G2D-1 → APPHOT-1 (and DIFFAST-1 plate solution)",
          [{"key": k, "policy": ((meas[k][1].get("data") or {}).get("flag_summary") or {}).get("policy"),
            "centroid_method": ((meas[k][1].get("data") or {}).get("centroid") or {}).get("method"),
            "photometry_method": ((meas[k][1].get("data") or {}).get("photometry") or {}).get("method"),
            "plate": ((meas[k][1].get("data") or {}).get("plate") or {}).get("method")} for k in keys if k in meas][:6],
          units={"unit_conversion": "surface brightness (MJy/sr) × pixel solid angle → flux density (µJy) via 1e12 × Ω_pix",
                 "coordinates": "pixel (x, y) → affine plate solution → tangent plane (ξ, η) in mas at a fixed tangent point; parallax offset applied if apply_parallax"},
          events=[i for i, _ in mv])
    stage("measured", bool(mv), "per-exposure values with uncertainty", [{"key": k, "flux_ujy": ids.get(f"meas:{k}", {}).get("flux_ujy"),
                                                                          "flux_err_ujy": ids.get(f"meas:{k}", {}).get("flux_err_ujy"),
                                                                          "fingerprint": canon.digest({"d": ids.get(f"meas:{k}", {}).get("flux_ujy")})[:12]} for k in keys][:8],
          units={"flux": "µJy", "position": "px → mas"})
    analysed = sorted(i for i in up if i.startswith(("pair:", "epoch:", "fit:", "scale:", "pos:")))
    stage("analysed", bool(analysed) or result_id.startswith("claim:data_quality"), "comparisons, visit means, motion fit, error scale",
          [{"id": i, "status": ids[i]["status"], "label": ids[i]["label"][:120]} for i in analysed if not i.startswith("pos:")][:12],
          note=f"{len([i for i in analysed if i.startswith('pair:')])} comparisons, {len([i for i in analysed if i.startswith('pos:')])} positions")
    down = epi.trace(graph, result_id, "forward")["nodes"]
    inf = [f"inf:{result_id[6:]}"] if result_id.startswith("claim:") else sorted(x["id"] for x in down if x["id"].startswith("inf:"))
    a = ev.get("assess", [])
    stage("assessed", bool(a) and bool(inf), "ASSESS-2 rules with fixed thresholds", [{"id": i, "label": ids.get(i, {}).get("label", "")[:160]} for i in inf],
          events=[a[0][0]] if a else [])
    claims = [result_id] if result_id.startswith("claim:") else [x["id"] for x in down if x["id"].startswith("claim:")]
    stage("claim", bool(claims), "statement of the outcome", [{"id": c, "statement": ids[c]["label"], "status": ids[c]["status"]} for c in claims])
    stage("report", bool(claims), "report.py renders each claim's recorded statement, criteria and limitations verbatim (Report Studio)",
          [{"renderer": "report.py", "record_content_hash": record.get("content_hash")}], note="the report is rendered from the record on demand; it adds no values")
    versions = {"analysis_version": P.get("analysis_version"), "methods": P.get("methods"), "software": record.get("software")}
    changes = []
    for k, v in (software_now or {}).items():
        was = (record.get("software") or {}).get(k)
        if was is not None and v is not None and was != v:
            changes.append({"package": k, "recorded": was, "now": v})
    missing = [s["stage"] for s in S if not s["present"]]
    return {"method": METHOD, "result": result_id, "stages": S, "missing": missing, "versions": versions, "dependency_changes": changes,
            "complete": not missing, "note": "Every stage refers to a recorded event or manifest entry; a missing stage is shown as missing."}
