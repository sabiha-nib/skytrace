"""Write docs/EPISTEMIC_METHODS.md: the Phase 8 methods (EPI-1, METHOD-DNA-1, SCICOMP-1, SCIDEBUG-1, KBOUND-1, CLAIMX-1,
NEG-1, BLIND-1, UFLOW-1, LINEAGE-1, MODELS-1, FUTURE-1, NEXTX-1, QFORGE-1, INTEG-1, REVIEWX-1, REPROX-1, SIMCHECK-1,
VAULT-1 and the browser-side PROTOCOL-1, BLINDLAB-1, ARG-1), generated from the code and from running them on the two
synthetic fixtures.

    python scripts/gen_epistemic_methods.py

Prose is written here; every table comes from the code (rules, stages, checks, modes, methods) or from executing the
methods through the same report the API serves. Fixture results are known-answer checks of the software on generated data,
not facts about the sky.
"""

from __future__ import annotations

import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "src"))

from skytrace import (analysis, blindspot, bundle as bmod, claims, decide, epistemic as epi, integrity, lineage, methodgenome as mg,  # noqa: E402
                      negspace, reprox, reviewx, scicomp, scidebug, simcheck, uflow)
from skytrace.server import epistemic as se  # noqa: E402

FIXTURES = ["syn-var-1", "syn-hpm-1"]


def esc(s) -> str:
    return str(s).replace("|", "\\|").replace("\n", " ")


def table(head, rows):
    return ["| " + " | ".join(head) + " |", "|" + "---|" * len(head)] + ["| " + " | ".join(esc(c) for c in r) + " |" for r in rows] + [""]


def report(tid):
    b = bmod.load(bmod.SYNTHETIC_ROOT / tid)
    rec = json.loads(json.dumps(analysis.run(b, {}).to_dict(), default=str))
    return rec, se.epistemic_report({"record": rec, "target_id": tid}), b


def main() -> int:
    R = {t: report(t) for t in FIXTURES}
    o = ["# Epistemic methods (Phase 8)", "",
         "Generated by `python scripts/gen_epistemic_methods.py` from the code and from the epistemic report the API serves for the two "
         "synthetic fixtures. Fixture results are known-answer checks of the software on generated data; they are not facts about the sky. "
         "No method here calls a model, uses a probability or produces a score.", ""]

    # EPI-1
    o += ["## EPI-1 — scientific objects, epistemic statuses and the reasoning graph", "",
          f"Fifteen object kinds: {', '.join(epi.KINDS)}. Ten statuses: {', '.join(epi.STATUSES)}. Each status comes from one rule that reads the "
          "object's origin and the method that produced it, never the wording of a sentence. Transformations and methods are procedures "
          "and carry no status. A trace is a breadth-first search over data edges, backward (what a result rests on) or forward (what depends on it).", ""]
    o += table(["Rule", "Statement"], epi.STATUS_RULES.items())
    rows = []
    for t, (rec, d, _) in R.items():
        G = d["graph"]
        kinds = {}
        for n in G["nodes"]:
            kinds[n["kind"]] = kinds.get(n["kind"], 0) + 1
        rows.append([t, len(G["nodes"]), len(G["edges"]), ", ".join(f"{k} {v}" for k, v in sorted(kinds.items()))])
    o += table(["Fixture", "Objects", "Edges", "By kind"], rows)
    o += ["The wording check (used by compiler check C1, the claim-wording stress mode and firewall check I12) is negation-aware: an outcome word "
          f"preceded within four words, in the same sentence, by one of {', '.join(sorted(epi.NEGATORS))} is not an assertion. It can flag a "
          "sentence for review; it never sets a status.", ""]

    # METHOD-DNA-1
    GEN = R[FIXTURES[0]][1]["genome"]
    o += ["## METHOD-DNA-1 — method genome", "",
          "Every analysis method is described by typed inputs and outputs (with units), assumptions, parameters, formula, dependencies, "
          "applicability, unsupported data, limitations, validation data, version chain and its known-answer tests. Health checks that the "
          "named tests exist and that determinism is covered. **Tests check the software against known answers; they do not establish "
          "scientific validity.**", ""]
    o += table(["Method", "Family", "Inputs → outputs", "Depends on", "Known-answer tests defined", "Used in syn-var-1", "Missing documentation"],
               [[m["id"], m["family"], ", ".join(i["name"] for i in m["inputs"]) + " → " + ", ".join(i["name"] for i in m["outputs"]),
                 ", ".join(m["dependencies"]) or "—", f"{m['health']['n_defined']} of {len(m['known_answer_tests'])}", "yes" if m["used_in_run"] else "no",
                 ", ".join(m["health"]["documentation_missing"]) or "none"] for m in GEN["methods"]])

    # SCICOMP-1
    o += ["## SCICOMP-1 — scientific compiler", "",
          f"Ten stages: {', '.join(n for _, n in scicomp.STAGES)}. Every check states its rule and returns pass, warning, fail or not applicable. "
          f"Outcomes: {', '.join(scicomp.OUTCOMES)}.", "", f"Precedence: {scicomp.OUTCOME_RULE}", "",
          "Every result carries the statement: *" + R[FIXTURES[0]][1]["compile"]["meaning"] + "*", ""]
    rows = []
    for t, (_, d, _) in R.items():
        c = d["compile"]
        rows.append([t, c["outcome"]] + [" / ".join(str(s["counts"][k]) for k in ("pass", "warning", "fail")) for s in c["stages"]])
    o += table(["Fixture", "Outcome"] + [s["name"] for s in R[FIXTURES[0]][1]["compile"]["stages"]], rows)
    o += ["Stage counts are pass / warning / fail.", ""]
    o += table(["Check", "Stage", "Rule"], [[c["id"], c["stage"], c["rule"]] for c in R[FIXTURES[0]][1]["compile"]["checks"]])

    # SCIDEBUG-1
    o += ["## SCIDEBUG-1 — scientific debugger", "",
          "Breakpoints exist only at execution stages the record contains. Inspecting a result recomputes it from recorded inputs with the "
          "method's formula; a value that was not recorded is reported as not recorded, never reconstructed. Differential debugging compares "
          f"two runs stage by stage in pipeline order and reports the earliest divergence; values agree within a relative tolerance of {scidebug.REL_EQUIV}.", ""]
    o += table(["Stage", "Name", "Recorded steps"], [[s, n, ", ".join(st)] for s, n, st in scidebug.STAGES])
    rows = []
    for t, (_, d, _) in R.items():
        for rid, ins in d["inspect"].items():
            if rid.startswith(("claim:", "fit:")):
                rows.append([t, rid, ins.get("verdict") or ins.get("agreement") or "—"])
    o += table(["Fixture", "Result", "Recomputation"], rows)

    # KBOUND-1 / CLAIMX-1
    o += ["## KBOUND-1 — knowledge boundary", "", f"Regions: {', '.join(claims.REGIONS)}. They are rule outcomes, not confidence levels.", ""]
    o += table(["Rule", "Statement"], claims.REGION_RULES.items())
    o += table(["Fixture"] + claims.REGIONS, [[t] + [d["boundary"]["counts"][r] for r in claims.REGIONS] for t, (_, d, _) in R.items()])
    o += ["## CLAIMX-1 — claim stress tests", "", f"Results: {', '.join(claims.RESULTS)}. Every mode has one documented rule.", ""]
    first = next(iter(R[FIXTURES[0]][1]["stress"].values()))
    o += table(["Mode", "Rule"], [[m["name"], m["rule"]] for m in first["modes"]])
    rows = []
    for t, (_, d, _) in R.items():
        for q, s in d["stress"].items():
            rows.append([t, q] + [s["counts"][k] for k in claims.RESULTS])
    o += table(["Fixture", "Claim"] + claims.RESULTS, rows)

    # NEG-1 / BLIND-1
    o += ["## NEG-1 — negative knowledge", "", f"Categories: {', '.join(negspace.CATEGORIES)}. Distinctions kept apart: {', '.join(negspace.DISTINCTIONS)}. "
          "Each entry records what was attempted, why, what happened, the inputs, the failure, what remains unknown, whether it can be repeated "
          "and what would unblock it.", ""]
    o += table(["Fixture"] + negspace.CATEGORIES, [[t] + [d["negative"]["counts"][c] for c in negspace.CATEGORIES] for t, (_, d, _) in R.items()])
    o += ["## BLIND-1 — blindspots", "", "Coverage is counted over the defined checks below and reported per check; no completeness percentage is given. "
          "Session-dependent checks are refined in the browser.", ""]
    o += table(["Check", "Name", "Rule"], blindspot.CHECKS)
    o += table(["Fixture"] + blindspot.STATES, [[t] + [d["blindspot"]["counts"][s] for s in blindspot.STATES] for t, (_, d, _) in R.items()])

    # UFLOW-1 / LINEAGE-1
    d0 = R[FIXTURES[0]][1]
    o += ["## UFLOW-1 — uncertainty flow", "", "Only the categories the methods represent; every omission is listed.", ""]
    o += table(["Node", "Category", "Quantity", "Unit", "Propagation"], [[n["id"], n["category"], n["quantity"], n["unit"], n["propagation"]] for n in d0["uflow"]["nodes"]])
    o += ["Not propagated:", ""] + table(["Step", "What", "Recorded as"], [[x["step"], x["what"], x["recorded_as"]] for x in d0["uflow"]["not_propagated"]])
    o += ["## LINEAGE-1 — data lineage", "", f"Stages: {', '.join(lineage.STAGES)}. A stage the record does not contain is reported missing, never filled.", ""]
    rows = []
    for t, (_, d, _) in R.items():
        for rid, L in d["lineage"].items():
            rows.append([t, rid, ", ".join(f"{s['stage']}: {'present' if s['present'] else 'missing'}" for s in L["stages"])])
    o += table(["Fixture", "Result", "Stages"], rows)

    # MODELS-1 / FUTURE-1
    o += ["## MODELS-1 — model arena", "", "M0 (static position) against M1 (linear motion) per axis on the same visits, assuming independent Gaussian "
          "errors. Criteria: χ², degrees of freedom, χ²ν, Δχ², AIC and leave-one-visit-out. No p-values, no scores; a better fit is not a physical explanation.", ""]
    rows = []
    for t, (_, d, _) in R.items():
        M = d["models"]
        if not M["available"]:
            rows.append([t, "—", "not available", "", "", ""])
            continue
        for ax, A in M["axes"].items():
            rows.append([t, ax, f"{A['delta_chi2']:.4g}", A["delta_k"], f"{A['delta_aic']:.4g}", "reproduces the pipeline fit" if A["validation"].get("agrees") else "does not reproduce"])
    o += table(["Fixture", "Axis", "Δχ²", "Δk", "ΔAIC", "Validation"], rows)
    o += ["## FUTURE-1 — FutureLab", "", "Hypothetical only. The weighted least-squares slope error is first checked against the recorded σ; scenarios "
          "are shown only if it reproduces. Nothing here is a scheduled observation.", ""]
    o += table(["Fixture", "Formula validated", "Scenarios"], [[t, d["future"]["validation"]["valid"], ", ".join(s["title"] for s in d["future"]["scenarios"])] for t, (_, d, _) in R.items()])

    # NEXTX / QFORGE
    o += ["## NEXTX-1 and QFORGE-1 — next steps and questions", "", f"Order: {decide.ORDER_RULE}. No optimality is claimed; each record says why it "
          "is not ranked higher.", "", f"Question categories: {', '.join(decide.CATEGORIES)}.", ""]
    o += table(["Fixture", "Recommendations"] + decide.CATEGORIES, [[t, len(d["next"]["recommendations"])] + [d["questions"]["counts"][c] for c in decide.CATEGORIES] for t, (_, d, _) in R.items()])

    # INTEG-1 / REVIEWX-1
    o += ["## INTEG-1 — integrity firewall", "", "Export-readiness advice on a text, checked against the record. It never blocks an export and never changes the text. "
          "Outcome: ready, ready with warnings, or needs attention.", ""]
    o += table(["Check", "Severity", "Name", "Rule"], integrity.CHECKS)
    o += table(["Fixture", "Investigation report"], [[t, d["report_check"]["outcome"]] for t, (_, d, _) in R.items()])
    o += ["## REVIEWX-1 — review board", "", "Eight automated perspectives over the compiler's checks, the stress tests, the report check and the genome. "
          "Each item links to the evidence it examined. This is not peer review; comments and responses are yours.", ""]
    o += table(["Perspective", "Name", "Compiler checks"], [[p[0], p[1], ", ".join(p[2]) if len(p) > 2 and isinstance(p[2], list) else "—"] for p in reviewx.PERSPECTIVES])

    # REPROX-1
    o += ["## REPROX-1 — independent reproduction", "", f"Verdicts: {', '.join(reprox.VERDICTS)}. Exact reproduction requires an identical re-execution "
          "and a record whose hash recomputes; documented differences require a recorded cause (software, parameters or inputs).", ""]
    rows = []
    for t, (rec, _, b) in R.items():
        r = reprox.reproduce(rec, b.path)
        rows.append([t, r["verdict"]])
    o += table(["Fixture", "Verdict"], rows)

    # SIMCHECK-1 / browser methods
    o += ["## SIMCHECK-1 — simulation audit", "", f"Generator identity, seeds, ground truth, noise and physical assumptions, simplifications and the "
          f"validity domain, plus a repeated-seed test (up to {simcheck.MAX_SEEDS} seeds). A synthetic benchmark tests the software against its own "
          "generator; it is not an observational validation dataset.", "",
          "Noise assumptions: " + "; ".join(simcheck.NOISE) + ".", "", "Simplifications: " + "; ".join(simcheck.SIMPLIFICATIONS) + ".", "",
          "## Browser-side methods", "",
          "* **VAULT-1** (`session.py`, `sessioncore.js`): each history entry's link is SHA-256(previous link + canonical entry). Edits break the chain "
          "and are refused on save; corrections are new entries. Tamper-evident, not a signature.",
          "* **PROTOCOL-1** (`protocolui.js`): hypotheses, inputs, exclusions, parameters, expected outcomes and robustness tests; lock with content hash and "
          "time, labelled when results were visible; append-only amendments. Not preregistration.",
          "* **BLINDLAB-1** (`protocolui.js`, `main.js`): hidden fields, a commitment hash, covered workspaces (renderers not called), copilot paused, ruler "
          "emphasis off; unblinding needs a locked protocol and typed confirmation; every step in the history.",
          "* **ARG-1** (`argueui.js`): arguments from graph objects with a fixed list of inference rules; logical validity and empirical standing are "
          "reported separately.", ""]
    (ROOT / "docs" / "EPISTEMIC_METHODS.md").write_text("\n".join(o) + "\n")
    print("wrote docs/EPISTEMIC_METHODS.md", sum(len(x) for x in o), "chars")
    return 0


if __name__ == "__main__":
    sys.exit(main())
