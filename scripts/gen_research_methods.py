"""Write docs/RESEARCH_METHODS.md: the Phase 6 methods (SESSION-1, PLAN-1, COMPAT-1, SEQ-1, DQ-1, LEDGER-1, RADAR-1,
EXP-1, MISSION-1, WF-1, ACQ-2, the capability registry) and the browser-side FIG-2, KG-1 and NOTE-1.

    python scripts/gen_research_methods.py [--no-experiments]

Prose is written here; every table is generated from the code (rules, templates, limits, registries) and from running
the methods on the two synthetic fixtures, so the documented behaviour is the executed behaviour. Fixture results are
known-answer checks of the methods, not facts about the sky. --no-experiments skips the EXP-1 runs (they re-run the
analysis many times) and says so in the document.
"""

from __future__ import annotations

import json
import sys
import time
from collections import Counter
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "src"))

from skytrace import (analysis, bundle as bmod, capabilities, compat, connectors, experiments, hypotheses, ledger,  # noqa: E402
                      missions, planner, quality, radar, session, workflows)
from skytrace.view import InvestigationView, evidence_graph  # noqa: E402

FIXTURES = ["syn-var-1", "syn-hpm-1"]


def esc(s) -> str:
    return str(s).replace("|", "\\|").replace("\n", " ")


def run(tid):
    b = bmod.load(bmod.SYNTHETIC_ROOT / tid)
    rec = json.loads(json.dumps(analysis.run(b, {}).to_dict(), default=str))
    return b, rec


def main() -> int:
    do_exp = "--no-experiments" not in sys.argv
    runs = {tid: run(tid) for tid in FIXTURES}
    rep = {}
    for tid, (b, rec) in runs.items():
        v = InvestigationView(rec, b.discovery, b.manifest, b.inspection)
        g = evidence_graph(v, tid)
        c = compat.report(rec, b.discovery, b.manifest)
        q = quality.checks(rec, b.manifest, b.discovery, bmod.SYNTHETIC_ROOT / tid)
        L = ledger.build(rec, g, b.discovery)
        r = radar.scan(rec, c, q, L, hypotheses.evaluate(rec), network=False)
        rep[tid] = (c, q, L, r)

    out = ["# Research methods (Phase 6, v0.6)", "",
           "Generated by `python scripts/gen_research_methods.py`: prose is written in that script; every table is produced from the "
           "code and from running the methods on the synthetic fixtures `syn-var-1` (injected brightness change) and `syn-hpm-1` "
           "(injected high proper motion). Fixture results are known-answer checks of the methods, **not facts about the sky**.", "",
           "None of these methods measures anything new. They organise, check and plan around the deterministic analysis "
           "(`analysis.py`, `science/`), whose methods are documented in `SCIENTIFIC_METHODS.md` and `DISCOVERY_METHODS.md`. "
           "No method here produces a probability or a score.", ""]

    # ------------------------------------------------------------------ SESSION-1
    out += ["## SESSION-1 — research session", "",
            f"A session (`{session.SCHEMA_ID}`) holds the question, attached runs (by content hash), hypotheses with versions, notebook blocks, "
            "annotations, plans, experiments, missions, workflows, examined pairs and an append-only history. It is validated by SCHEMA-1 "
            "(the same declarative schema in `schema.py` and `web/js/schema.js`) and hashed as SHA-256 of its SKY-CANON-1 text without "
            "`content_hash`. Imports whose stated hash differs are refused; an import never overwrites an existing id. Saved 0.5 records "
            "migrate into sessions; the original record is kept.", "",
            f"* Size limit: {session.MAX_BYTES:,} bytes of canonical text.",
            f"* Notebook block types ({len(session.BLOCK_TYPES)}): " + ", ".join(session.BLOCK_TYPES) + ".",
            f"* Reference kinds: " + ", ".join(session.REF_KINDS) + ".",
            f"* Plan-step statuses: " + ", ".join(session.STEP_STATUS) + ".", ""]

    # ------------------------------------------------------------------ CAPREG-2
    reg = capabilities.registry()
    out += [f"## Capability registry and actions ({reg['version']})", "",
            "Introduced in Phase 6 as CAPREG-2; Phase 7 (CAPREG-3) added six actions and a permission class per action, documented in "
            "`FRONTIER_METHODS.md`. The table below is the current registry.", "",
            f"Registry version `{reg['version']}`: {len(reg['capabilities'])} capabilities and {len(capabilities.ACTIONS)} executable actions. "
            "The planner, workflows, Discovery Radar and missions execute only these actions (the copilot's plan tool proposes them and "
            "executes none); an action names its capabilities, "
            "preconditions, outputs, whether it needs confirmation, its cost, and where it can run in the static preview "
            "(`browser`: recomputed in the page; `precomputed`: recorded at build time; `unavailable`: refused with a reason).", "",
            "| Action | Title | Capabilities | Preconditions | Confirm | Cost | Static preview |", "|---|---|---|---|---|---|---|"]
    for a in capabilities.ACTIONS:
        out.append(f"| `{a['id']}` | {esc(a['title'])} | {', '.join(a['capabilities'])} | {esc(', '.join(a['preconditions'])) or '—'} | "
                   f"{'yes' if a['confirm'] else 'no'} | {a['cost']} | {a['static']} |")
    out.append("")

    # ------------------------------------------------------------------ PLAN-1
    S = planner.SPEC
    out += ["## PLAN-1 — Adaptive Investigation Planner", "",
            "A question is matched against ordered ASCII rules (first match wins) to an intent; the intent selects a template of "
            "registered actions; each step's status is decided from the facts the caller supplies (server or browser, loaded run, "
            "selected pair, network). Steps marked *confirm* wait for confirmation; inspection steps end as `needs_review` until a "
            "person writes what they saw. A model may propose an intent, but it is used only if `validate_intent` accepts it; the "
            "browser port (`web/js/planner.js`) is parity-tested against this code.", "",
            "| Order | Intent | Pattern |", "|---:|---|---|"]
    for i, (k, pat) in enumerate(S["rules"], 1):
        out.append(f"| {i} | {k} | `{esc(pat)}` |")
    out += ["", "| Template | Steps (id: action; *optional*; ← depends) |", "|---|---|"]
    for k, steps in S["templates"].items():
        out.append(f"| {k} | " + "; ".join(f"{sid}: `{act}`{' *optional*' if opt else ''}{' ← ' + ', '.join(dep) if dep else ''}"
                                               f"{' (needs a pair)' if cond == 'pair' else ''}" for sid, act, opt, dep, cond in steps) + " |")
    out += ["", "Questions the registered methods cannot answer are refused with the reason and what would be needed:", "",
            "| Intent | Question | Why not | Needed |", "|---|---|---|---|"]
    for k, qid in S["unanswerable_map"].items():
        u = S["unanswerable"][qid]
        out.append(f"| {k} | {esc(u['text'])} | {esc(u['why'])} | {esc(u['needed'])} |")
    facts = {"has_target_data": True, "has_run": True, "run_hash": "0" * 64, "pair": None, "server": True, "static": False, "network": False, "targets": []}
    out += ["", "Plans for the planner's example questions (server facts, a loaded run, no pair selected, no network):", "",
            "| Question | Intent | Steps (status) |", "|---|---|---|"]
    for qq in S["examples"]:
        p = planner.plan(qq, facts)
        out.append(f"| {esc(qq)} | {p['intent']['kind']} | " + ", ".join(f"{s['id']} ({s['status']})" for s in p["steps"]) + " |")
    out.append("")

    # ------------------------------------------------------------------ COMPAT-1 / SEQ-1
    out += ["## COMPAT-1 and SEQ-1 — observation compatibility and sequences", "",
            "COMPAT-1 reads the WLMATCH-2 decisions already logged in the record and lays them out as a matrix; it never re-decides "
            "a pair. Reason codes:", "", "| Code | Meaning |", "|---|---|"]
    for k, v in compat.CODES.items():
        out.append(f"| {k} | {esc(v)} |")
    out += ["", "Exposures are grouped into visits by time. SEQ-1 sequences are sets of observations on one detector in which "
            "every pair is accepted (cliques of the accepted-pair graph, built greedily in time order); playback runs only over a "
            "sequence, never interpolates, and states when a sequence spans only two visits. Coverage gaps are intervals of at least "
            "30 days between visits on a detector. Duplicates are observations whose files share a SHA-256.", "",
            "| Fixture | Observations | Pairs | Accepted | Sequences (≥ 3 obs) | Longest sequence: obs / visits | Coverage gaps | Duplicates |",
            "|---|---:|---:|---:|---:|---|---:|---:|"]
    for tid, (c, q, L, r) in rep.items():
        seqs = c["sequences"]
        cnt = c["matrix"]["counts"]
        longest = max(seqs, key=lambda s: s["n_frames"]) if seqs else None
        gaps = sum(len(d["gaps"]) for d in c["coverage"]["per_detector"].values())
        out.append(f"| {tid} | {len(c['observations'])} | {sum(cnt.values())} | {cnt.get('accepted', 0)} | {sum(s['n_frames'] >= 3 for s in seqs)} | "
                   f"{(str(longest['n_frames']) + ' / ' + str(longest['n_visits'])) if longest else '—'} | {gaps} | {len(c['duplicates'])} |")
    out.append("")

    # ------------------------------------------------------------------ DQ-1
    q0 = rep[FIXTURES[0]][1]
    out += ["## DQ-1 — data-quality checks", "",
            "Each check states its rule and reports one of: " + ", ".join(quality.OUTCOMES) + ". The outcomes are listed in order of "
            "severity; a check's outcome is the most severe of its items. There is **no overall score**: the checks are reported "
            "separately because they are not commensurable.", "", "| Check | Name | Rule |", "|---|---|---|"]
    for ch in q0["checks"]:
        out.append(f"| {ch['id']} | {esc(ch['name'])} | {esc(ch['rule'])} |")
    out += ["", "| Fixture | " + " | ".join(ch["id"] for ch in q0["checks"]) + " |", "|---|" + "---|" * len(q0["checks"])]
    for tid, (c, q, L, r) in rep.items():
        by = {ch["id"]: ch["outcome"] for ch in q["checks"]}
        out.append(f"| {tid} | " + " | ".join(by.get(ch["id"], "—").replace("_", " ") for ch in q0["checks"]) + " |")
    out += ["", "The fixtures' `invalid` and `incompatible` outcomes are deliberate: the fixtures include flagged exposures and "
            "wavelength-mismatched pairs so that the checks have something to find. Injected defects (altered hashes, missing "
            "fields, wrong units) are tested in `tests/unit/test_research_os.py`.", ""]

    # ------------------------------------------------------------------ LEDGER-1
    out += ["## LEDGER-1 — evidence ledger", "",
            "For each claim the ledger counts direct evidence items, wavelength-matched comparisons, observations and detectors "
            "reached from the claim in the evidence graph. A claim resting on one item is flagged as such; one linked item is never "
            "reported as full support. Absence outcomes (" + ", ".join(sorted(ledger.ABSENCE)) + ") are statements about sensitivity "
            "and are not flagged for lacking positive support. Contradictions are found by four fixed rules: C1 raw significance at or "
            "above the threshold but the calibrated, error-scaled one below (or the reverse); C2 two motion fits differing by more than "
            "3σ; C3 measured motion differing from the catalogue by more than 3σ; C4 tests of one explanation disagreeing.", "",
            "| Fixture | Claim | Category | Direct | Comparisons | Observations | Detectors | Flags |", "|---|---|---|---:|---:|---:|---:|---|"]
    for tid, (c, q, L, r) in rep.items():
        for cl in L["claims"]:
            s = cl["support"]
            out.append(f"| {tid} | {cl['id']} | {cl['category']} | {s['direct']} | {s['comparisons']} | {s['observations']} | {len(s['detectors'])} | "
                       f"{esc('; '.join(cl['flags'])) or '—'} |")
    out += ["", "| Fixture | Contradictions by rule | Completeness gaps |", "|---|---|---|"]
    for tid, (c, q, L, r) in rep.items():
        n = Counter(x["rule"] for x in L["contradictions"])
        out.append(f"| {tid} | {', '.join(f'{k}: {v}' for k, v in sorted(n.items())) or 'none'} | "
                   f"{esc('; '.join(f'{k}: {v}' for k, v in L['completeness']['counts'].items())) or 'none'} |")
    out.append("")

    # ------------------------------------------------------------------ RADAR-1
    doc = radar.__doc__.split("Signals")[1].split("Ranking")[0]
    out += ["## RADAR-1 — Discovery Radar", "",
            "The radar lists **research opportunities**, not detections. Each item states what it proposes, why, the evidence, the "
            "data it needs, the action that would carry it out, what it cannot establish, and whether it can run here and now.", "",
            "```", "Signals" + doc.rstrip(), "```", "",
            f"Ranking: runnable items first, then signal order {' → '.join(radar.ORDER)}; ties keep the record's order. The order is a "
            "stated convention, not a computed value.", "", "| Fixture | Items | By signal | Runnable now |", "|---|---:|---|---:|"]
    for tid, (c, q, L, r) in rep.items():
        n = Counter(x["signal"] for x in r["items"])
        out.append(f"| {tid} | {len(r['items'])} | {', '.join(f'{k}: {n[k]}' for k in radar.ORDER if n[k])} | {sum(1 for x in r['items'] if x['can_run_now'])} |")
    out.append("")

    # ------------------------------------------------------------------ EXP-1
    out += ["## EXP-1 — Experiment Studio", "",
            f"Templates and their pass criteria (at most {experiments.MAX_RUNS} analysis runs per experiment):", "",
            "| Template | Title | Criterion |", "|---|---|---|"]
    for k, t in experiments.TEMPLATES.items():
        out.append(f"| {k} | {esc(t['title'])} | {esc(t['criterion'])} |")
    out += ["", "Robustness settings (the bounds the server accepts): " + "; ".join(l for l, _ in experiments.ROBUSTNESS) + ".", "",
            f"> {experiments.VALIDITY}", ""]
    if do_exp:
        out += ["| Fixture | Experiment | Criterion met | Runs |", "|---|---|---|---:|"]
        cfgs = [{"template": "reproducibility"}, {"template": "method_comparison"}, {"template": "negative_control", "question": "variability"},
                {"template": "negative_control", "question": "motion"}, {"template": "robustness"}]
        load = lambda t: bmod.load(bmod.SYNTHETIC_ROOT / t)  # noqa: E731
        for tid in FIXTURES:
            for cfg in cfgs:
                t0 = time.perf_counter()
                res = experiments.run(load, tid, cfg)
                ev = res.get("evaluation", {})
                passed = ev.get("passed")
                label = "yes" if passed is True else "no" if passed is False else "not available (" + esc(ev.get("detail") or res.get("status", "")) + ")"
                out.append(f"| {tid} | {cfg['template']}{(' (' + cfg['question'] + ')') if 'question' in cfg else ''} | {label} | {len(res.get('runs', []))} |")
                print(f"  {tid} {cfg} -> {passed} ({time.perf_counter() - t0:.1f}s)", file=sys.stderr)
        out += ["", "A method comparison that is not met is the expected result when reference calibration changes which pairs are "
                "significant; the experiment reports the difference, it does not decide which method is right. A negative control runs on a *different* fixture in which the effect is absent by construction; "
                "with two fixtures, syn-var-1 has no motion control and syn-hpm-1 no variability control, and those are reported as not "
                "available rather than imitated.", ""]
    else:
        out += ["Experiment runs were skipped for this build of the document (`--no-experiments`).", ""]

    # ------------------------------------------------------------------ MISSION-1 / WF-1 / ACQ-2
    out += ["## MISSION-1 — missions", "",
            "Missions are guided task lists without points, streaks or badges. Completion is read from the session (events, question, "
            "runs, notebook content, hypotheses with tests, written reviews); a mission cannot be marked complete by hand.", "",
            "| Mission | Objective | Prerequisites | Tasks (criterion) |", "|---|---|---|---|"]
    for m in missions.MISSIONS:
        out.append(f"| {esc(m['title'])} | {esc(m['objective'])} | {esc('; '.join(m['prerequisites']))} | " +
                   "; ".join(f"{esc(t['title'])} ({', '.join(t['criterion'])})" for t in m["tasks"]) + " |")
    out += ["", "## WF-1 — workflows", "",
            f"A workflow (`{workflows.SCHEMA_ID}`) declares its targets (≤ {workflows.MAX_TARGETS}), steps (≤ {workflows.MAX_STEPS}) and "
            f"at most {workflows.MAX_EXECUTIONS} executions in total; every step is a registered action and dependencies must precede. "
            "Execution keeps a per-item record (status, error, result summary); cancellation stops before the next step and keeps "
            "completed items; retry runs only items that failed or were cancelled. Templates: " +
            ", ".join(esc(t["name"]) for t in workflows.TEMPLATES) + ".", "",
            "## ACQ-2 — connectors", "",
            "Each connector's request is built by the same function the acquisition uses, with a recorder in place of the network, "
            "so the preview is exactly what would be sent; nothing is sent. Availability comes from `data/environment_report.json`; "
            "in this environment every service is refused by the proxy, so acquisition is BLOCKED and no real-data result exists.", "",
            "| Connector | Service | Endpoint | Provides | Response handling |", "|---|---|---|---|---|"]
    for cn in connectors.CONNECTORS:
        out.append(f"| {cn['id']} | {esc(cn['service'])} | `{cn['endpoint']}` | {esc(cn['provides'])} | {esc(cn['response'])} |")
    out += ["", "Lifecycle: " + "; ".join(f"{k}: {esc(v)}" for k, v in connectors.LIFECYCLE.items()) + ".", ""]

    # ------------------------------------------------------------------ browser-side methods
    out += ["## Browser-side methods (FIG-2, KG-1, NOTE-1)", "",
            "* **FIG-2** (`web/js/figurestudio.js`): figures drawn only from recorded values — observation timeline, flux per sequence, "
            "z histogram, positions, data-quality outcomes, sensitivity. Each states its title, units, data source, method and the run's "
            "content hash; SVG export embeds that metadata. No PDF export is offered.",
            "* **KG-1** (`web/js/kg.js`): links saved records and sessions only by stored facts — K1 names the same target, K2 identical "
            "content hash, K3 a session uses a saved run, K4 same analysis version, K5 the same non-clean data-quality category. With "
            "fewer than two records or sessions it shows an empty state. No relationship carries a confidence value.",
            "* **NOTE-1** (`web/js/notebook.js`): blocks are text (yours) or references to recorded items, resolved against the active "
            "run when shown and exported; assistant drafts stay labelled until accepted. Markdown export labels every block "
            "[you] / [recorded] / [draft]; the session package is a deterministic stored ZIP (`web/js/zipstore.js`).", "",
            "Browser ports checked against this code by parity tests: planner (its rules are served from `/api/specs`, so both use one "
            "table), missions, workflows, session validation and hashing (`tests/unit/test_research_os.py`, `tests/unit/test_research_session.py`).", ""]

    (ROOT / "docs" / "RESEARCH_METHODS.md").write_text("\n".join(out) + "\n")
    print("wrote docs/RESEARCH_METHODS.md")
    return 0


if __name__ == "__main__":
    sys.exit(main())
