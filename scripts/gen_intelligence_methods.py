"""Write docs/INTELLIGENCE_METHODS.md: the Phase 9 methods (SCI-ENTITY-1, MEMORY-1, DGENOME-1, UNKNOWN-1, ADV-1, GATE-1, DEBT-1,
ORACLE-1, EVNEG-1, CAUSAL-1, MDNET-1, REPRONET-1, WHATIF-1, FINGERPRINT-1, INSTCHECK-1, BUDGET-1, CYCLE-1 and the browser-side
CAPSULE-1), generated from the code and from running the intelligence report the API serves on the two synthetic fixtures.

    python scripts/gen_intelligence_methods.py

Prose is written here; every rule table comes from the modules and every fixture table from executing them. Fixture results are
known-answer checks of the software on generated data, not facts about the sky.
"""

from __future__ import annotations

import json
import sys
from collections import Counter
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "src"))

from skytrace import (adversary, analysis, autonomy, budget, bundle as bmod, capabilities, causal, dgenome, entities as E, fingerprint, gate,  # noqa: E402
                      instcheck, mdnet, memory, oracle, repronet, unknownmap, whatif)
from skytrace.server import app as sapp, intelligence as si  # noqa: E402

FIXTURES = ["syn-var-1", "syn-hpm-1"]


def esc(s) -> str:
    return str(s).replace("|", "\\|").replace("\n", " ")


def table(head, rows):
    return ["| " + " | ".join(head) + " |", "|" + "---|" * len(head)] + ["| " + " | ".join(esc(c) for c in r) + " |" for r in rows] + [""]


def run(tid):
    b = bmod.load(bmod.SYNTHETIC_ROOT / tid)
    rec = json.loads(json.dumps(analysis.run(b, {}).to_dict(), default=str))
    iid = f"doc-{tid}"
    sapp.INVESTIGATIONS[iid] = {"record": rec, "target_id": tid}
    return iid


def main() -> int:
    iids = {t: run(t) for t in FIXTURES}
    entries = si.corpus_entries()
    corpus = si.corpus_from(entries)
    R = {}
    for t, iid in iids.items():
        e = sapp.INVESTIGATIONS[iid]
        R[t] = (si.intelligence_report(e), si.unknown_for(e, entries))
    o = ["# Scientific intelligence methods (Phase 9)", "",
         "Generated by `python scripts/gen_intelligence_methods.py` from the code and from the intelligence report the API serves for the two "
         "synthetic fixtures (`syn-var-1`, a variable source; `syn-hpm-1`, a high-proper-motion source). Fixture results are known-answer checks "
         "of the software on generated data; they are not facts about the sky. No method here calls a model, uses a probability or produces a "
         "score. The browser ports of the session-dependent rules (`web/js/intelcore.js`) are parity-tested against these modules "
         "(`tests/unit/test_intelligence.py::test_browser_intelligence_functions_match_python`).", ""]

    o += ["## SCI-ENTITY-1 — the shared entity envelope", "",
          f"{len(E.TYPES)} entity types share one envelope: a stable id, a version, provenance references, a creation time, an epistemic status "
          "and a validation result. Graph objects keep the status EPI-1 gave them; other objects take a status from these rules:", ""]
    o += table(["Rule", "Statement"], E.RULES.items())
    o += table(["Fixture", "Entities", "Types present", "Validation errors"],
               [(t, r["entities"]["summary"].get("n", len(r["entities"]["items"])), len({x["type"] for x in r["entities"]["items"]}), len(r["entities"]["errors"]))
                for t, (r, _) in R.items()])

    o += ["## MEMORY-1 — research memory", "",
          f"Memory items are of kinds {', '.join(memory.KINDS)}, with statuses {', '.join(memory.STATUSES)}. A competing explanation stays "
          "'provisional' however often it is remembered as consistent: memory never turns a hypothesis into a fact. Recall maps query words "
          f"onto a fixed vocabulary of {len(memory.CONCEPTS)} concepts. Failure warnings quote the recorded reason when an action you are "
          "about to take failed before on the same target.", ""]
    o += table(["Rule", "Statement"], memory.STATUS_RULES.items())
    mc = Counter(i["status"] for i in corpus["memory"]["items"])
    o += [f"Corpus at generation time ({corpus['n']} investigations: the fixtures plus any saved records): " + ", ".join(f"{k} {v}" for k, v in sorted(mc.items())) + ".", ""]

    o += ["## DGENOME-1 — discovery genome", "",
          f"Thirteen fields per question, each citing graph objects or record paths: {', '.join(dgenome.FIELDS)}. Comparison is structural "
          "(shared characteristics, interpretations, weaknesses, uncertainty structure, reusable methods) and carries no score; a match is "
          "not evidence that two sources are physically alike.", ""]

    o += ["## UNKNOWN-1 — the unknown-universe map", "", "Eight regions; every item is placed by the first rule that matches and states its basis.", ""]
    o += table(["Region", "Rule", "Statement"], [(n, r, unknownmap.RULES[r]) for _, n, r in unknownmap.REGIONS])
    o += table(["Fixture"] + [n for _, n, _ in unknownmap.REGIONS], [(t, *[len(next(x for x in u["regions"] if x["id"] == rid)["items"]) for rid, _, _ in unknownmap.REGIONS])
                                                                   for t, (_, u) in R.items()])

    o += ["## ADV-1 — the scientific adversary", "",
          "The challenge ledger is organised by eight questions. Each entry names the rule that raised it (ASL-1 challenges, CLAIMX-1 stress "
          "modes, HYPO-1 explanations, INSTCHECK-1 checks); no entry is raised without a rule. An entry is 'resolved' only with a reference "
          "to a recorded item.", ""]
    o += table(["Question", "Text"], adversary.QUESTIONS)
    rows = []
    for t, (r, _) in R.items():
        it = [i for c in r["adversary"]["conclusions"] for q in c["questions"] for i in q["items"]]
        sev = Counter(i["severity"] for i in it)
        rows.append((t, len(it), ", ".join(f"{k} {v}" for k, v in sorted(sev.items()))))
    o += table(["Fixture", "Challenges", "By severity"], rows)

    o += ["## GATE-1 and DEBT-1 — integrity gate and research debt", "",
          "Eight requirements must be met before an investigation can be marked complete. 'Ready to mark complete' means the requirements "
          "are met; it does not mean the conclusions are true.", ""]
    o += table(["Fixture"] + [f"{g} {n}" for g, n in gate.REQUIREMENTS] + ["Outcome", "Debt items"],
               [(t, *[next(x for x in r["gate"]["requirements"] if x["id"] == g)["state"] for g, _ in gate.REQUIREMENTS], r["gate"]["outcome"], len(r["debt"]["items"]))
                for t, (r, _) in R.items()])

    o += ["## ORACLE-1 and EVNEG-1 — observation oracle and evidence negotiation", "",
          f"Hypothetical observation plans are evaluated under the measurement model that reproduces the recorded fit (threshold {oracle.THRESHOLD} σ, "
          f"at most {oracle.MAX_ADDED} added visits). The expected Δχ² between the hypotheses is S² + 1 for a significance S. Information gain in "
          "bits is not computed, because it needs prior probabilities that no record defends. Plans are never presented as scheduled observations.", ""]
    rows = []
    for t, (r, _) in R.items():
        for q, p in r["oracle"]["examples"].items():
            rows.append((t, q, "available" if p and p.get("available") else "not available", "; ".join(p.get("ranking", [])) if p else "—"))
    o += table(["Fixture", "Question", "Model", "Example ranking"], rows)

    o += ["## CAUSAL-1 — causality lab", "",
          f"A documented causal graph of the measurement process ({len(causal.VARIABLES)} variables, {len(causal.EDGES)} edges) is an assumption, "
          "not something learned from the data. Each candidate model is assessed on five separate criteria; C5 (experimentally supported) "
          "is never met, because archival data allow no intervention on the sky.", ""]
    o += table(["Criterion", "Name"], causal.CRITERIA)

    o += ["## MDNET-1 — multi-discovery network", "", "A relationship exists only where a rule matches; each edge states its basis and limitation. Shared keywords never create an edge.", ""]
    o += table(["Rule", "Relationship", "Limitation"], [(k, v[0], v[1]) for k, v in mdnet.RULES.items()])
    o += [f"Corpus at generation time: {len(corpus["network"]["edges"])} edge(s).", ""]

    o += ["## REPRONET-1 — reproduction network", "",
          "A manifest records data hashes, software and environment, configuration, seed, stage hashes and limitations. Two manifests compare "
          f"into one of: {', '.join(repronet.CLASSES)}. A matching re-execution shows that a result repeats, not that it is valid.", ""]

    o += ["## WHATIF-1 — what-if engine", "",
          "Each of six questions is answered only where a valid method exists; otherwise the engine says 'no valid method'. Scenarios are "
          "hypothetical; the baseline is recomputed and hash-checked and the record is never modified.", ""]
    o += table(["Fixture"] + [f"{w}" for w, _ in whatif.QUESTIONS], [(t, *[next((x["kind"] for x in r["whatif"]["questions"] if x["id"] == w), "—") for w, _ in whatif.QUESTIONS])
                                                                  for t, (r, _) in R.items()])
    o += table(["Question", "Text"], whatif.QUESTIONS)

    o += ["## FINGERPRINT-1, INSTCHECK-1 and BUDGET-1", "",
          f"The sensitivity fingerprint recomputes each conclusion along six dimensions ({', '.join(n for _, n in fingerprint.DIMENSIONS)}) and "
          f"reports {', '.join(fingerprint.STATES)}, never a score. The instrumental reality check covers {', '.join(instcheck.NAMES.values())}; "
          "ruling every one out does not make a signal astrophysical. The uncertainty budget classes every term as "
          f"{', '.join(budget.CLASSES)}; variance shares are given only where terms add in quadrature (the PAIRDIFF-2 denominator).", ""]
    rows = []
    for t, (r, _) in R.items():
        fp = Counter(d["state"] for q in r["fingerprint"]["questions"] for d in q["dimensions"])
        rows.append((t, ", ".join(f"{k} {v}" for k, v in sorted(fp.items())), ", ".join(f"{k} {v}" for k, v in r["budget"]["counts"].items())))
    o += table(["Fixture", "Fingerprint states", "Budget classes"], rows)

    o += ["## CYCLE-1 — research cycle with bounded autonomy", "",
          "The cycle proposes registered actions only, by these rules. Advisory executes nothing; supervised executes each step you approve; "
          "restricted automation runs the predefined workflow after one authorization. No level grants network or write permission.", ""]
    o += table(["Rule", "Statement"], autonomy.RULES.items())
    o += table(["Level", "Permission classes allowed", "Executes"], [(v["name"], ", ".join(v["allows"]) or "none", v["executes"]) for v in capabilities.AUTONOMY_LEVELS])
    o += [f"Restricted workflow: {', '.join(capabilities.RESTRICTED_WORKFLOW)}.", ""]
    rows = []
    for t, (r, u) in R.items():
        cy = autonomy.propose(r, u)
        rows.append((t, ", ".join(f"{p['rule']}→{p['action']}" for p in cy["proposals"])))
    o += table(["Fixture", "Proposals"], rows)

    o += ["## CAPSULE-1 — time capsule (browser)", "",
          "A capsule freezes the record hash, the gate, the unknown map and the session items at a moment, with a SHA-256 digest of its content. "
          "A digest makes later edits detectable; it is not a signature and not cryptographic immutability.", ""]
    (ROOT / "docs" / "INTELLIGENCE_METHODS.md").write_text("\n".join(o) + "\n")
    for iid in iids.values():
        sapp.INVESTIGATIONS.pop(iid, None)
    print("wrote docs/INTELLIGENCE_METHODS.md")
    return 0


if __name__ == "__main__":
    sys.exit(main())
