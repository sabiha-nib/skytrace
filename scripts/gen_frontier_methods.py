"""Write docs/FRONTIER_METHODS.md: the Phase 7 methods (CF-1, SYNOBS-1, OBSDES-1, ASL-1, INFO-1, REPRO-1, REVIEW-1,
TWIN-1, SPE-1, HORIZON-1, CAPREG-3) generated from the code and from running them on the two synthetic fixtures.

    python scripts/gen_frontier_methods.py [--no-synthetic]

Prose is written here; every table comes from the code (rules, bounds, presets, templates, checks) or from executing the
methods. Fixture and generated-scenario results are known-answer checks of the software, not facts about the sky, and
agreement on generated data does not establish performance on real SPHEREx data. --no-synthetic skips generating the
Synthetic Observatory templates (each writes a bundle under a temporary directory and runs the analysis) and says so.
"""

from __future__ import annotations

import json
import os
import sys
import tempfile
from collections import Counter
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "src"))
os.environ.setdefault("SKYTRACE_SYNTHLAB_DIR", tempfile.mkdtemp(prefix="skytrace-synthlab-"))

from skytrace import (adversarial, analysis, bundle as bmod, capabilities, counterfactual as cf, discovery, infogain, ledger,  # noqa: E402
                      possibility, quality, radar, repro, review, synthobs, twin)
from skytrace.server.research import compat  # noqa: E402
from skytrace.view import InvestigationView, evidence_graph  # noqa: E402

FIXTURES = ["syn-var-1", "syn-hpm-1"]


def esc(s) -> str:
    return str(s).replace("|", "\\|").replace("\n", " ")


def ctx(tid):
    b = bmod.load(bmod.SYNTHETIC_ROOT / tid)
    rec = json.loads(json.dumps(analysis.run(b, {}).to_dict(), default=str))
    v = InvestigationView(rec, b.discovery, b.manifest, b.inspection)
    g = evidence_graph(v, tid)
    disc = discovery.report(rec, b.discovery, b.manifest, {})
    q = quality.checks(rec, b.manifest, b.discovery, b.path)
    L = ledger.build(rec, g, b.discovery)
    c = compat.report(rec, b.discovery, b.manifest)
    res = {"compat": c, "quality": q, "ledger": L, "radar": radar.scan(rec, c, q, L, disc["hypotheses"], network=False)}
    hyp, unc = disc["hypotheses"], disc["uncertainty"]
    asl = adversarial.challenges(rec, hyp, q, L, unc, None, None, None)
    info = infogain.analyse(hyp, True)
    spe = possibility.layers(rec, disc, res, info, asl, None, True, False)
    rp = repro.audit(rec, b.path, rerun=True)
    rv = review.review(rec, q, L, hyp, unc, rp, asl, None, None)
    return {"b": b, "rec": rec, "asl": asl, "info": info, "spe": spe, "repro": rp, "review": rv}


def summ(L: dict) -> str:
    """A layer's summary as short text: scalars as `k: v`, lists and dicts by size; design layers by item count."""
    sm = L.get("summary")
    if not sm:
        return f"{len(L.get('items', []))} item(s)"
    parts = []
    for k, v in sm.items():
        if isinstance(v, (list, dict)):
            if k == "claims":
                parts.append("claims: " + ", ".join(f"{c['id'].split(':')[-1]} = {c['category']}" for c in v))
            elif k == "hypotheses":
                parts.append("explanations: " + ", ".join(f"{n} {o}" for o, n in Counter(v.values()).items()))
            elif k in ("detectors", "releases", "counterfactual_kinds", "synthetic_templates", "experiment_templates"):
                parts.append(f"{k}: {', '.join(map(str, v))}")
            elif isinstance(v, dict) and all(not isinstance(x, (list, dict)) for x in v.values()):
                parts.append(f"{k}: " + ", ".join(f"{a} {b}" for a, b in v.items()))
            else:
                parts.append(f"{k}: {len(v)}")
        else:
            parts.append(f"{k}: {v}")
    return "; ".join(parts)


def main() -> int:
    do_syn = "--no-synthetic" not in sys.argv
    C = {tid: ctx(tid) for tid in FIXTURES}
    load = lambda t: bmod.load(bmod.SYNTHETIC_ROOT / t)  # noqa: E731
    out = ["# Frontier methods (Phase 7, v0.7)", "",
           "Generated by `python scripts/gen_frontier_methods.py`. Prose is written in that script; every table is produced from the code or "
           "by running the methods on the synthetic fixtures `syn-var-1` (injected brightness change) and `syn-hpm-1` (injected high proper "
           "motion) and on generated Synthetic Observatory scenarios. These are known-answer checks of the software, **not facts about the sky**; "
           "agreement on generated data does not establish performance on real SPHEREx observations.", "",
           "None of these methods measures anything new, produces a probability or a score, or calls a model. They re-assess recorded inputs, "
           "re-run the deterministic pipeline on stated changes, generate labelled synthetic data, or apply documented rules to a finished record.", "",
           "| Method | Module | What it does | What it never does |", "|---|---|---|---|"]
    for m, mod, what, never in [
        ("CF-1", "counterfactual.py", "One stated change against a named baseline (parameter, exclusion, threshold, error scale, method); re-runs or re-assesses and compares.", "Modify the original record or bundle; present a simulated value as observed."),
        ("SYNOBS-1", "synthobs.py", "Generates a bounded scenario as a SYNTHETIC bundle under data/synthlab, runs the unchanged pipeline, compares with ground truth.", "Write to data/bundles or fixtures; replace observations."),
        ("OBSDES-1", "synthobs.py", "Generates 2–3 hypothetical schedules with the same truth and compares recovered sensitivity and outcomes.", "Schedule a telescope; claim instrument performance."),
        ("ASL-1", "adversarial.py", "Challenges from documented rules over the record, hypotheses, quality, ledger, uncertainty, stability and session.", "Claim a flaw no rule establishes; hide a challenge you acknowledged."),
        ("INFO-1", "infogain.py", "Orders open hypothesis tests by feasibility and the viable explanations they bear on.", "Compute information gain (there is no probability model)."),
        ("REPRO-1", "repro.py", "Eleven checks and one of four verdicts; replay compared by content hash.", "Count a successful import as reproduction; produce a score."),
        ("REVIEW-1", "review.py", "Five deterministic reviewer rule sets; every finding cites a record field or session item.", "Simulate reviewers or agents."),
        ("TWIN-1", "twin.py", "Hashed, versioned computational records of an observation, target, analysis, scenario or session; structural diff.", "Model an astronomical object physically."),
        ("SPE-1 / HORIZON-1", "possibility.py", "Six investigation layers and research-opportunity cards from ten rules over recorded state.", "Invent counts or findings; rank by a hidden score."),
        ("CAPREG-3", "capabilities.py", "Registry with six new actions and a permission class per action; autopilot levels.", "Let a plan run an unregistered action or reach the network.")]:
        out.append(f"| {m} | `{mod}` | {what} | {never} |")

    # CF-1
    out += ["", "## CF-1 Counterfactual Universe Lab", "",
            "Bounds (from the code): thresholds " + ", ".join(f"`{k}` {lo}–{hi}" for k, (lo, hi) in cf.THRESHOLD_BOUNDS.items()) +
            f"; photometric error factor ({cf.ERROR_SCALE_BOUNDS[0]}, {cf.ERROR_SCALE_BOUNDS[1]}]; at most {cf.MAX_EXCLUDED_KEYS} excluded observation keys. "
            "Exclusion works on a copy of the bundle index (recorded as selection rejection `counterfactual_exclusion`); the files on disk are untouched. "
            "Threshold, error-scale and method scenarios re-assess the recorded inputs; with no change, re-assessment reproduces every recorded outcome exactly "
            "(tested on both fixtures).", "", "Value labels:", ""]
    out += [f"- **{k}** — {v}" for k, v in cf.LEGEND.items()]
    out += ["", "Prepared scenarios run on both fixtures (categories: brightness / motion):", "",
            "| Scenario | Kind | Fixture | Baseline | Counterfactual | Changed outputs | Baseline intact |", "|---|---|---|---|---|---:|---|"]
    for p in cf.PRESETS:
        for tid in FIXTURES:
            r = cf.run(load, tid, {"kind": p["kind"], "change": p["change"]}, baseline_record=C[tid]["rec"])
            if r.get("status") != "completed":
                out.append(f"| {esc(p['label'])} | {p['kind']} | `{tid}` | — | {esc(r.get('error') or r.get('status'))} | — | — |")
                continue
            bc, cc = r["baseline"]["categories"], r["counterfactual"]["categories"]
            fmt = lambda c: f"{c.get('variability', '—')} / {c.get('motion', '—')}"  # noqa: E731
            out.append(f"| {esc(p['label'])} | {p['kind']} | `{tid}` | {fmt(bc)} | {fmt(cc)} | {sum(x['changed'] for x in r['comparison'])} | {'yes' if r['baseline']['intact'] else 'NO'} |")

    # SYNOBS-1
    out += ["", "## SYNOBS-1 Synthetic Observatory", "",
            f"Detector positions (target y, which sets the wavelength sampled): " + ", ".join(f"{k} = {v} px" for k, v in synthobs.POSITIONS.items()) +
            f". Files carry `SYNTHETIC = T` and a fixed provenance stamp `{synthobs.FIXED_STAMP}` so the same scenario and seed give identical bytes "
            "and the same record hash. The expected outcome for each question is a stated rule applied to the ground truth and the pipeline's own reported "
            "sensitivity; a verdict is `agrees`, `disagrees`, `not determinable` or `not confirmed (calibration-limited …)`.", ""]
    if do_syn:
        out += ["| Template | Seed | Brightness verdict | Motion verdict | Refused exposures | Record hash |", "|---|---:|---|---|---|---|"]
        for t in synthobs.TEMPLATES:
            r = synthobs.run(t["scenario"])
            v = {x["question"]: x["verdict"] for x in r["evaluation"]["rows"]}
            fb = r["evaluation"]["failure_behaviour"]["rejected_exposures_by_reason"]
            out.append(f"| {esc(t['title'])} | {t['scenario']['seed']} | {v.get('variability', '—')} | {v.get('motion', '—')} | "
                       f"{', '.join(f'{n} {k}' for k, n in fb.items()) or 'none'} | `{r['record_content_hash'][:12]}` |")
        out += ["", "The blend template is a deliberate failure case: a reference star crosses the target's path and the pipeline refuses the "
                "blended exposures rather than measuring them."]
    else:
        out += ["*Templates not generated in this run (`--no-synthetic`).*"]

    # OBSDES-1
    out += ["", "## OBSDES-1 Observation Design Lab", "",
            f"At most {synthobs.DESIGN_MAX} hypothetical schedules, each generated with the same truth and seed and analysed by the unchanged pipeline. "
            "The output compares recovered 5σ motion sensitivity and outcome categories. Skytrace does not schedule or command a telescope and the noise "
            "model is illustrative; the brief says so."]
    if do_syn:
        base = synthobs.TEMPLATES[0]["scenario"]
        d = synthobs.design({"seed": base["seed"], "pm_mas_yr": base["pm_mas_yr"]}, [
            {"name": "two passes, 6 months, same position", "passes": [{"day": 0, "position": "A", "brightness": 1}, {"day": 182, "position": "A", "brightness": 1}]},
            {"name": "four passes over 18 months", "passes": base["passes"]}])
        out += ["", "| Schedule | Passes | Span (d) | Motion 5σ sensitivity (mas/yr) | Motion |", "|---|---:|---:|---:|---|"]
        for x in d["schedules"]:
            s = x["motion_sensitivity_mas_yr"]
            out.append(f"| {esc(x['name'])} | {x['n_passes']} | {x['span_days']:.0f} | {'—' if s is None else f'{s:.0f}'} | {x['motion_category']} ({x['motion_verdict']}) |")

    # ASL-1
    out += ["", "## ASL-1 Adversarial Science Lab", "", "Modes: " + "; ".join(f"**{k}** {v}" for k, v in adversarial.MODES.items()) + ".", "",
            "Severity is fixed per rule (" + ", ".join(adversarial.SEVERITY) + "), not scored. A challenge is *open* until examined; acknowledging it "
            "with a note keeps it visible. A challenge is raised only when a rule's condition holds on recorded values.", "",
            "| Fixture | Challenge | Mode | Severity | Issue |", "|---|---|---|---|---|"]
    for tid in FIXTURES:
        for c in C[tid]["asl"]["challenges"]:
            out.append(f"| `{tid}` | {c['id']} | {c['mode_name']} | {c['severity']} | {esc(c['issue'])} |")

    # INFO-1
    out += ["", "## INFO-1 Information analysis", "", C[FIXTURES[0]]["info"]["interpretation_limits"], "",
            f"Ranking rule: {C[FIXTURES[0]]['info']['ranking_rule']}", "", "| Fixture | # | Test | Feasibility | Bears on (viable) |", "|---|---:|---|---|---|"]
    for tid in FIXTURES:
        for c in C[tid]["info"]["candidates"]:
            out.append(f"| `{tid}` | {c['rank']} | {c['test']} | {c['feasibility']} | {esc(', '.join(c['bears_on']))} |")

    # REPRO-1
    out += ["", "## REPRO-1 Reproducibility challenge", "",
            "Importing a record proves only that it parses. The verdict is *reproduced* only when a re-execution here gives the identical content hash "
            "and every other check passes; *replayable, not replayed here* when nothing failed but no replay ran; *not reproducible as recorded* when a "
            "replay or integrity check failed; *incomplete* when inputs or required metadata are missing.", "", "| Check | Name | Rule | " +
            " | ".join(f"`{t}`" for t in FIXTURES) + " |", "|---|---|---|" + "---|" * len(FIXTURES)]
    res = {tid: {x["id"]: x for x in C[tid]["repro"]["checks"]} for tid in FIXTURES}
    for cid, name, rule in repro.CHECKS:
        out.append(f"| {cid} | {name} | {esc(rule)} | " + " | ".join(res[t].get(cid, {}).get("status", "—") for t in FIXTURES) + " |")
    out.append("| | **Verdict** | | " + " | ".join(f"**{C[t]['repro']['verdict']}**" for t in FIXTURES) + " |")

    # REVIEW-1
    out += ["", "## REVIEW-1 Review room", "", "Roles are software rule sets, not people or agents: " + ", ".join(review.ROLES.values()) +
            ". Causal or discovery words flagged in your notes: " + ", ".join(f"`{w}`" for w in review.CAUSAL_WORDS) + ".", "",
            "| Fixture | Role | Findings | Outcomes |", "|---|---|---:|---|"]
    for tid in FIXTURES:
        by = {}
        for f in C[tid]["review"]["findings"]:
            by.setdefault(f["role"], []).append(f["outcome"])
        for role, outs in by.items():
            out.append(f"| `{tid}` | {review.ROLES.get(role, role)} | {len(outs)} | {', '.join(f'{n} {k}' for k, n in Counter(outs).items())} |")

    # TWIN-1
    out += ["", "## TWIN-1 Astro-twins", "", twin.SEMANTICS, "", "Sections: " + ", ".join(twin.SECTIONS) + ". Kinds: " + ", ".join(twin.KINDS) + ".", "",
            "| Fixture | Kind | Content hash | Verifies | Derived from |", "|---|---|---|---|---|"]
    for tid in FIXTURES:
        for t in (twin.analysis_twin(C[tid]["rec"]), twin.target(C[tid]["b"].target, C[tid]["rec"])):
            out.append(f"| `{tid}` | {t['kind']} | `{t['content_hash'][:12]}` | {'yes' if twin.verify(t) else 'NO'} | {len(t.get('derived_from', []))} hash(es) |")

    # SPE-1 / HORIZON-1
    out += ["", "## SPE-1 Scientific Possibility Engine and HORIZON-1 Discovery Horizon", "",
            "Six layers, each computed from recorded values. Opportunity categories:", ""]
    out += [f"- **{k}** {v}" for k, v in possibility.CATS.items()]
    out += ["", "Feasibility classes, in ranking order: " + " → ".join(possibility.FEAS) + ". Within a class, cards follow the category order. "
            "This is a stated convention, not a value.", "", "| Fixture | Layer | Summary |", "|---|---|---|"]
    for tid in FIXTURES:
        for L in C[tid]["spe"]["layers"]:
            out.append(f"| `{tid}` | {L['n']}. {esc(L['name'])} ({esc(L['method'])}) | {esc(summ(L))} |")
    out += ["", "| Fixture | Card | Category | Feasibility | Question |", "|---|---|---|---|---|"]
    for tid in FIXTURES:
        for c in C[tid]["spe"]["horizon"]["cards"]:
            out.append(f"| `{tid}` | {c['id']} | {c['category']} | {c['feasibility']} | {esc(c['question'])} |")

    # CAPREG-3
    reg = capabilities.registry()
    out += ["", "## CAPREG-3 Actions and permissions", "", f"Registry version `{reg['version']}`. The autopilot runs only registered actions, only at a level "
            "that allows their permission class, and only after you authorize the listed steps. No level grants network access; imported workflows never run "
            "on import.", "", "| Level | Allows |", "|---|---|"]
    for lv in reg["autopilot_levels"]:
        out.append(f"| {lv['id']} | {esc(', '.join(lv['allows']) or 'nothing runs')} |")
    out += ["", "| Action | Permission |", "|---|---|"]
    for a, p in sorted(capabilities.PERMISSION.items()):
        out.append(f"| `{a}` | {p} |")
    (ROOT / "docs" / "FRONTIER_METHODS.md").write_text("\n".join(out) + "\n")
    print("wrote docs/FRONTIER_METHODS.md", len(out), "lines")
    return 0


if __name__ == "__main__":
    sys.exit(main())
