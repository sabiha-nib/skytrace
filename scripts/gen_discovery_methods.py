"""Write docs/DISCOVERY_METHODS.md: the Phase 5 methods (CAPREG-1, DISC-1, HYPO-1, UNC-1, REGDIAG-1, PKG-1).

    python scripts/gen_discovery_methods.py

Prose is written here; every table is generated from the code (rules, questions, registry) and from running the
methods on the two synthetic fixtures, so the documented behaviour is the executed behaviour. The fixture results are
known-answer checks of the method, not facts about the sky.
"""

from __future__ import annotations

import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "src"))

from skytrace import analysis, bundle as bmod, capabilities, discovery, hypotheses, uncertainty  # noqa: E402
from skytrace.view import InvestigationView, registration_diagnostics  # noqa: E402

FIXTURES = ["syn-var-1", "syn-hpm-1"]


def run(tid):
    b = bmod.load(bmod.SYNTHETIC_ROOT / tid)
    rec = json.loads(json.dumps(analysis.run(b, {}).to_dict(), default=str))
    return b, rec


def md_escape(s):
    return str(s).replace("|", "\\|").replace("\n", " ")


def main() -> int:
    runs = {tid: run(tid) for tid in FIXTURES}
    L = ["# Discovery methods (Phase 5, v0.5)", "",
         "Generated by `python scripts/gen_discovery_methods.py`: prose is written in that script; every table is produced from "
         "the code and from running the methods on the synthetic fixtures `syn-var-1` (injected brightness change) and "
         "`syn-hpm-1` (injected high proper motion). Fixture results are known-answer checks of the methods, **not facts about "
         "the sky**.", "",
         "All six methods read a finished investigation record (and, for the inventory, the bundle manifest). None of them "
         "measures anything, calls a network service or a language model, or produces a probability. Each is versioned; the "
         "version appears in every output it produces.", "",
         "| Method | Module | What it does |", "|---|---|---|",
         "| CAPREG-1 | `capabilities.py` | Registry of what Skytrace can do: methods, inputs, bounded parameters, outputs, limitations, tests, and where it runs (local / server / network), with current availability. |",
         "| DISC-1 | `discovery.py` | Discovery engine stages A–G: evidence inventory, registered research questions with test plans, review links, rule-based next steps, record. |",
         "| HYPO-1 | `hypotheses.py` | Competing explanations, each with deterministic tests over recorded values; six statuses; one published overall rule. |",
         "| UNC-1 | `uncertainty.py` | What each recorded uncertainty is made of; bounds kept as bounds; sensitivity (STAB-1) kept separate; unquantified effects named. |",
         "| REGDIAG-1 | `view.py` | Geometry of a pair's registration from the two Gaia-referenced plate solutions. |",
         "| PKG-1 | `package.py` | Deterministic reproducibility package with checksums. |", ""]

    # CAPREG-1
    reg = capabilities.registry({"server": True, "network": False})
    L += ["## CAPREG-1 — capability registry", "",
          "Availability shown for this environment (server running, external services blocked). The static preview publishes "
          "its own view of the registry: server-only capabilities are marked unavailable there, browser ports are named.", "",
          "| ID | Capability | Methods | Runs | Available here | Tests |", "|---|---|---|---|---|---|"]
    for c in reg["capabilities"]:
        L.append(f"| `{c['id']}` | {md_escape(c['name'])} | {', '.join(c['methods']) or '—'} | {c['execution']} | "
                 f"{'yes' if c['available'] else 'no' if c['available'] is False else 'unknown'} | {', '.join('`'+t+'`' for t in c['tests'])} |")
    L.append("")

    # DISC-1
    L += ["## DISC-1 — discovery engine", "",
          "**A · Inventory.** One row per evidence item (target, reference catalogue, every archive record, the run) with source, "
          "origin, epoch, channel, SHA-256 from the bundle manifest, quality and limitations. A field that is not recorded stays "
          "empty and is counted (`unknown_fields`); a field that does not apply is marked *not applicable*. Nothing is guessed.", "",
          "**B · Questions.** A question is *answerable* when every required input is present, *answerable with limits* when some "
          "are, and *not answerable* when none are. Three questions are registered as not answerable by design.", "",
          "| ID | Question | Required inputs | Method |", "|---|---|---|---|"]
    for q in discovery.QUESTIONS:
        L.append(f"| {q['id']} | {md_escape(q['text'])} | {md_escape('; '.join(r[0] for r in q['requires']))} | {md_escape(q['method'])} |")
    for q in discovery.UNANSWERABLE:
        L.append(f"| {q['id']} | {md_escape(q['text'])} | not answerable: {md_escape(q['why'])} | — |")
    L += ["", "Status on the fixtures:", "", "| Question | " + " | ".join(FIXTURES) + " |", "|---|" + "---|" * len(FIXTURES)]
    qs = {tid: {q["id"]: q for q in discovery.questions(rec)} for tid, (_, rec) in runs.items()}
    for q in [*discovery.QUESTIONS, *discovery.UNANSWERABLE]:
        L.append(f"| {q['id']} | " + " | ".join(qs[t][q["id"]]["status"] for t in FIXTURES) + " |")
    L += ["", "**C · Test plan** per question: required inputs (available / missing), method versions, preconditions, assumptions, "
          "expected outputs, validation and limitations. **D · Execution** links each plan to the workspace where it runs; the "
          "engine does not execute anything itself. **E · Review** links outcomes (ASSESS-2), the evidence matrix (HYPO-1) and the "
          "uncertainty decomposition (UNC-1). **F · Next steps** are rules over outcomes, inventory and registry; each states the "
          "question it addresses, the data it needs, what it can and cannot establish, and the service it needs when that service "
          "is unavailable. No step promises a gain in confidence. **G · Record**: the research question and user hypotheses are "
          "saved with the investigation; the package adds inventory, tests and checksums.", ""]
    for tid, (b, rec) in runs.items():
        h = hypotheses.evaluate(rec)
        steps = discovery.next_steps(rec, h, {"server": True, "network": False})
        L += [f"Next steps on `{tid}`:", ""] + [f"{i}. {md_escape(s['action'])} — {md_escape(s['why'])}"
                                                + (f" (needs {s['requires_unavailable_service']})" if s["requires_unavailable_service"] else "")
                                                for i, s in enumerate(steps, 1)] + [""]

    # HYPO-1
    L += ["## HYPO-1 — hypothesis tests", "",
          f"Statuses: {', '.join(hypotheses.STATUSES)}. Overall rule (identical in `web/js/rules.js`, parity-tested over every "
          f"combination of up to three tests): *{hypotheses.OVERALL_RULE}*.", "",
          "A test reads values already in the record and applies the stated rule. Explanations without an implemented test are "
          "listed as *not tested* rather than omitted, so unequal evidence stays visibly unequal. User-written hypotheses are "
          "stored as interpretations and can only cite these recorded tests.", "",
          "| Explanation | Test | Rule | " + " | ".join(FIXTURES) + " |", "|---|---|---|" + "---|" * len(FIXTURES)]
    res = {tid: hypotheses.evaluate(rec) for tid, (_, rec) in runs.items()}
    first = res[FIXTURES[0]]
    for q in first["questions"]:
        for hx in q["hypotheses"]:
            for t in hx["tests"]:
                cells = []
                for tid in FIXTURES:
                    hq = next(x for x in res[tid]["questions"] if x["question"] == q["question"])
                    hh = next(x for x in hq["hypotheses"] if x["id"] == hx["id"])
                    tt = next(x for x in hh["tests"] if x["id"] == t["id"])
                    cells.append(tt["status"].replace("_", " "))
                L.append(f"| {hx['id']}: {md_escape(hx['statement'])} | {t['id']}: {md_escape(t['description'])} | {md_escape(t['rule'])} | " + " | ".join(cells) + " |")
    L += ["", "Overall per explanation:", "", "| Explanation | " + " | ".join(FIXTURES) + " |", "|---|" + "---|" * len(FIXTURES)]
    for q in first["questions"]:
        for hx in q["hypotheses"]:
            cells = [next(h for qq in res[t]["questions"] for h in qq["hypotheses"] if h["id"] == hx["id"])["overall"] for t in FIXTURES]
            L.append(f"| {hx['id']} | " + " | ".join(cells) + " |")
    L += ["", "Known-answer checks in `tests/unit/test_discovery.py`: the injected-motion fixture makes the catalogue-motion "
          "explanation consistent and the static and registration-artefact explanations contradicted; a copy of the variability "
          "fixture with an injected exposure-level gain change makes the calibration explanation consistent so far.", ""]

    # UNC-1
    L += ["## UNC-1 — uncertainty decomposition", "",
          "Motion: the statistical error of the primary (visit-averaged) fit, the per-exposure fit as a cross-check, the number of "
          "visits whose scatter used the empirical floor, the catalogue proper-motion error, and the parallax systematic converted "
          "to a rate bound over the baseline — labelled a **bound, not a standard deviation**, and never added in quadrature.", "",
          "Brightness: for each matched pair the PAIRDIFF-2 denominator is recomputed from its logged inputs (the two exposures' "
          "flux errors and the reference-ratio scatter), its variance shares are reported, and the recomputed z is compared with "
          "the logged z (`consistent_with_log`). Any mismatch is shown, not hidden.", "",
          "Sensitivity to analysis choices (STAB-1) is shown beside, never inside, a σ.", "",
          "Effects that no method here quantifies (listed in the interface and the package):", ""]
    L += [f"* **{u['name']}** — {u['why']}" for u in uncertainty.UNQUANTIFIED]
    L.append("")
    for tid, (_, rec) in runs.items():
        u = uncertainty.decompose(rec)
        v = u["variability"]
        ok = sum(1 for p in v.get("pairs", []) if p.get("consistent_with_log")) if v.get("available") else 0
        cal = sum(1 for p in v.get("pairs", []) if p.get("calibrated")) if v.get("available") else 0
        L.append(f"* `{tid}`: motion decomposition {'available' if u['motion']['available'] else 'not available'}; "
                 f"{v.get('n_pairs', 0)} matched pairs, the {len(v.get('pairs', []))} largest decomposed, "
                 f"{ok} of {cal} calibrated pairs recompute exactly to the logged z.")
    L.append("")

    # REGDIAG-1
    L += ["## REGDIAG-1 — registration diagnostics", "",
          "From each exposure's Gaia-referenced plate solution (linear part of the gnomonic fit): pixel scale along x and y "
          "(arcsec/px), x-axis position angle, number of reference stars and leave-one-out residual RMS (mas). For the pair: "
          "rotation and scale ratio of B relative to A, the target pixel in A, the pixel in B that sees the same sky point, and "
          "the shift. Geometric only; it says nothing about photometric calibration. The browser port (`web/js/static/compare.js`) "
          "is parity-tested against Python. The registration-limit test T-REG uses the same residuals: a motion is *registration "
          "limited* when 3 × the median plate RMS is at least |proper motion| × baseline.", ""]
    for tid, (b, rec) in runs.items():
        v = InvestigationView(rec)
        diags = [(d, registration_diagnostics(v.measure_events[d["a"]]["data"], v.measure_events[d["b"]]["data"])) for d in v.accepted_pairs()]
        ok = [(d, g) for d, g in diags if g.get("available")]
        L.append(f"* `{tid}`: diagnostics available for {len(ok)} of {len(diags)} accepted pairs (the rest lack a plate solution "
                 "for one exposure).")
        if ok:
            d, g = ok[0]
            r = g["relative"]
            L.append(f"  First such pair: rotation {r['rotation_deg']:.4f}°, scale ratio {r['scale_ratio']:.6f}, "
                     f"shift ({r['shift_px'][0]:.2f}, {r['shift_px'][1]:.2f}) px; plate RMS {g['a']['rms_mas']:.0f} and "
                     f"{g['b']['rms_mas']:.0f} mas.")
    L += ["", "## PKG-1 — reproducibility package", "",
          "`GET /api/investigations/{id}/package.zip` (and *Report Studio → Reproducibility package*). One folder "
          "`skytrace-<hash16>/` containing README.md, record.json (byte-identical to the record export), report.md, discovery.json, "
          "evidence_graph.json, capabilities.json, bundle_manifest.json and SHA256SUMS. Member order and timestamps are fixed, so the "
          "same inputs give the same bytes (tested). Verify with `sha256sum -c SHA256SUMS`; the record's content hash recomputes "
          "from record.json; replay needs the data bundle named in the manifest. No image data is included.", ""]
    (ROOT / "docs" / "DISCOVERY_METHODS.md").write_text("\n".join(L) + "\n")
    print("wrote docs/DISCOVERY_METHODS.md")
    return 0


if __name__ == "__main__":
    sys.exit(main())
