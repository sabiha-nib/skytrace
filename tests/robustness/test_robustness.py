"""Robustness of the analysis on SYNTHETIC variants with known truth.

Every bundle here is generated by skytrace.synthetic into a temporary directory and is labelled
synthetic. These tests check that each known failure mode is either corrected by the method designed
for it or reported by the assessment, never silently turned into a false claim.
"""

import copy
import math

import pytest

from skytrace import analysis, bundle as bmod, stability
from skytrace.synthetic import SPECS, build

HPM, VAR = SPECS[0], SPECS[1]


def variant(base, tmp_path, name, **opts):
    s = copy.deepcopy(base)
    s.update(opts)
    s["target_id"] = name
    d = build(s, tmp_path / name)
    v = bmod.verify(d)
    assert v["ok"] and v["kind"] == "synthetic", v["problems"]
    return bmod.load(d)


def run(b, **params):
    rec = analysis.run(b, params).to_dict()
    ev = {e["step"]: e for e in rec["events"]}
    outs = {o["question"]: o for o in ev["assess"]["data"]["outcomes"]}
    return rec, ev, outs


def pm_error(ev, truth):
    f = ev["astrometry"]["data"]["fit"]
    return math.hypot(f["pm_xi_mas_yr"] - truth[0], f["pm_eta_mas_yr"] - truth[1]), f


# ------------------------------------------------------------------ parallax
def test_parallax_corrected_motion(tmp_path, no_network):
    b = variant(HPM, tmp_path, "syn-plx", parallax_mas=800.0)
    _, ev_on, outs_on = run(b)
    _, ev_off, _ = run(b, apply_parallax=False)
    err_on, f_on = pm_error(ev_on, (HPM["pmra"], HPM["pmdec"]))
    err_off, _ = pm_error(ev_off, (HPM["pmra"], HPM["pmdec"]))
    assert outs_on["motion"]["category"] == "motion_detected"
    assert ev_on["astrometry"]["data"]["parallax"]["applied"] is True
    assert err_on < err_off, (err_on, err_off)
    assert abs(f_on["pm_xi_mas_yr"] - HPM["pmra"]) < 3 * f_on["sig_xi"]


# ------------------------------------------------------------------ calibration
def test_gain_change_is_not_variability(tmp_path):
    """A 25% exposure-level calibration change on a constant star: PAIRDIFF-1 flags it, PAIRDIFF-2 removes it."""
    b = variant(VAR, tmp_path, "syn-gain", variability=[1.0, 1.0, 1.0, 1.0], gain_by_pass=[1.0, 1.0, 1.25, 1.0])
    _, ev, outs = run(b)
    v = outs["variability"]
    assert v["evidence"]["max_abs_z_pairdiff1"] >= 5          # the raw comparison is fooled
    assert v["category"] != "variability_candidate", v["statement"]
    ratios = [p["differential"]["ratio_median"] for p in ev["variability"]["data"]["pairs"] if p["differential"].get("calibrated")]
    assert any(abs(r - 1.25) < 0.03 or abs(r - 0.8) < 0.03 for r in ratios)   # the gain is measured


def test_real_change_survives_gain_change(tmp_path):
    b = variant(VAR, tmp_path, "syn-gain-var", gain_by_pass=[1.0, 1.0, 1.25, 1.0])
    _, _, outs = run(b)
    assert outs["variability"]["category"] == "variability_candidate"


# ------------------------------------------------------------------ release mixing
def test_release_mixing_refused_for_photometry(tmp_path):
    b = variant(VAR, tmp_path, "syn-rel", release_by_pass=["SYNTHETIC-A", "SYNTHETIC-A", "SYNTHETIC-B", "SYNTHETIC-B"])
    rec, ev, outs = run(b)
    rel = {m["data"]["key"]: m["data"]["release"] for m in rec["events"] if m["step"] == "measure" and "release" in m["data"]}
    assert ev["pairs"]["data"]["rejection_reasons"].get("different_releases", 0) > 0
    assert all(rel[p["a"]] == rel[p["b"]] for p in ev["pairs"]["data"]["accepted"])
    # The dimming is only testable between pass 1 and pass 3 (same detector rows, same wavelength), which now
    # span two releases: the change is no longer claimed. Within release B, passes 3 and 4 sample different
    # wavelengths. This is the intended conservative trade-off.
    assert outs["variability"]["category"] != "variability_candidate"
    _, ev_mix, outs_mix = run(b, photometry_same_release=False)
    assert len(ev_mix["pairs"]["data"]["accepted"]) > len(ev["pairs"]["data"]["accepted"])
    assert outs_mix["variability"]["category"] == "variability_candidate"


# ------------------------------------------------------------------ reference stars
def test_bad_reference_stars_removed_by_ruwe(tmp_path):
    bad = [(3.0, 0.0, 2.6), (0.0, 3.0, 2.2), (-3.0, 0.0, 3.1), (2.0, 2.0, 1.9)]
    b = variant(HPM, tmp_path, "syn-refs", bad_refs=bad, ref_ruwe=1.0)
    _, ev, outs = run(b)
    sel = ev["references"]["data"]["selection"]
    assert sel["rejected"]["ruwe_high"] == 4 and sel["accepted_unchecked"]["ruwe_missing"] == 0
    assert outs["motion"]["category"] == "motion_detected"


def test_bad_reference_stars_without_flags_caught_per_exposure(tmp_path):
    bad = [(3.0, 0.0, None), (0.0, -3.0, None)]
    b = variant(HPM, tmp_path, "syn-refs2", bad_refs=bad)
    rec, ev, outs = run(b)
    rejected = [e["data"]["plate"]["rejected_refs"] for e in rec["events"]
                if e["step"] == "measure" and (e["data"].get("plate") or {}).get("rejected_refs")]
    assert rejected, "leave-one-out plate rejection should remove offset references"
    assert outs["motion"]["category"] in ("motion_detected", "registration_limited", "motion_inconsistent")
    assert outs["motion"]["category"] != "no_motion_at_sensitivity"


# ------------------------------------------------------------------ distortion
def test_unmodelled_distortion_shows_in_registration(tmp_path):
    base = run(bmod.load(bmod.SYNTHETIC_ROOT / "syn-hpm-1"))[2]["motion"]["evidence"]["median_plate_rms_mas"]
    b = variant(HPM, tmp_path, "syn-dist", unmodelled_sip=3e-4)
    _, _, outs = run(b)
    m = outs["motion"]
    assert m["evidence"]["median_plate_rms_mas"] > base          # visible in the registration diagnostic
    assert m["category"] in ("motion_detected", "registration_limited", "motion_inconsistent")


# ------------------------------------------------------------------ S/N and baseline
def test_low_snr_gives_no_false_candidate(tmp_path):
    b = variant(VAR, tmp_path, "syn-faint", target_flux_scale=0.03)
    _, _, outs = run(b)
    v, m = outs["variability"], outs["motion"]
    assert v["category"] != "variability_candidate"
    assert m["category"] in ("insufficient_evidence", "no_motion_at_sensitivity", "measurement_failed")
    if v["sensitivity"]:
        assert v["sensitivity"]["min_detectable_fractional_change_5sigma"] > 0.3


def test_single_visit_is_labelled(tmp_path):
    b = variant(HPM, tmp_path, "syn-1visit", passes=[HPM["passes"][0]], variability=[1.0])
    _, ev, outs = run(b)
    if ev["astrometry"]["status"] == "ok":
        assert ev["astrometry"]["data"]["fit_kind"] == "exposure"
        assert "single visit" in ev["astrometry"]["detail"]
    # 2.5 days of baseline cannot detect 4.7"/yr at these errors; never a false "static" proof
    assert outs["motion"]["category"] != "motion_detected" or outs["motion"]["evidence"]["detection_snr"] >= 5
    assert "not proof" in outs["motion"]["statement"] or outs["motion"]["category"] != "no_motion_at_sensitivity"


def test_two_passes_six_months(tmp_path):
    b = variant(HPM, tmp_path, "syn-2pass", passes=HPM["passes"][:2], variability=[1.0, 1.0], no_wave=[])
    _, ev, outs = run(b)
    assert ev["astrometry"]["data"]["fit_kind"] == "epoch" and ev["astrometry"]["data"]["fit"]["n_epochs"] == 2
    assert outs["motion"]["category"] in ("motion_detected", "no_motion_at_sensitivity", "registration_limited")


# ------------------------------------------------------------------ stability and determinism
def test_fixture_outcomes_stable_under_perturbation():
    for tid in ("syn-hpm-1", "syn-var-1"):
        r = stability.run(bmod.load(bmod.SYNTHETIC_ROOT / tid))
        assert all(r["stable"].values()), (tid, r["fragile_under"])


def test_generator_and_analysis_deterministic(tmp_path):
    a = variant(VAR, tmp_path, "syn-det-a", gain_by_pass=[1.0, 1.1, 1.0, 1.0])
    b = variant(VAR, tmp_path, "syn-det-b", gain_by_pass=[1.0, 1.1, 1.0, 1.0])
    ha = [bmod.sha256_file(p) for p in sorted((a.path / "images").glob("*.fits"))]
    hb = [bmod.sha256_file(p) for p in sorted((b.path / "images").glob("*.fits"))]
    assert ha == hb
